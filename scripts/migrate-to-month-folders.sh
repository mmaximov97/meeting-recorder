#!/usr/bin/env bash
# Разовая раскладка записей из корня по месячным папкам.
#
# Переносит ГРУППОЙ по общей основе имени: обе дорожки и .transcript-папка
# обязаны уехать вместе, иначе транскрипт развяжется с записью.
#
# Дата берётся из начала имени (^\d{4}-\d{2}-\d{2}) — без требования времени,
# чтобы переехало и положенное руками (например .mp4 с демо). Всё, у чего даты
# в имени нет, остаётся в корне.
#
# Идемпотентен: повторный запуск ничего не делает — в корне уже пусто.
#
# Имена переменных ASCII (moved/skipped/month), а не кириллицей: bash не
# поддерживает нелатинские идентификаторы ни в одной локали (проверено —
# `перенесено=0` падает как `command not found` даже под LC_ALL=ru_RU.UTF-8).
# Это ограничение самого bash, а не окружения. Текст и логика — как в брифе.
set -euo pipefail

ROOT="${1:-/mnt/c/Users/<username>/Recordings}"
DRY="${DRY_RUN:-0}"

cd "$ROOT"
moved=0
skipped=0

for entry in *; do
  [ -e "$entry" ] || continue
  [ -d "$entry" ] && [[ "$entry" =~ ^[0-9]{4}-[0-9]{2}$ ]] && continue

  if [[ "$entry" =~ ^([0-9]{4})-([0-9]{2})-[0-9]{2} ]]; then
    month="${BASH_REMATCH[1]}-${BASH_REMATCH[2]}"
    if [ "$DRY" = "1" ]; then
      echo "  $entry -> $month/"
    else
      mkdir -p "$month"
      mv -n -- "$entry" "$month/"
    fi
    moved=$((moved + 1))
  else
    echo "  оставлено в корне (нет даты в имени): $entry"
    skipped=$((skipped + 1))
  fi
done

echo "перенесено: $moved, оставлено: $skipped"
