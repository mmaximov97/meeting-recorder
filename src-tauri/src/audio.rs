/// Шаг цикла. В 10 раз чаще детекта — ради отзывчивости на команды из UI и
/// прокачки аудио из каналов захвата, а не ради самого детекта: детектор
/// опрашивается раз в `POLL_INTERVAL` (2 с), и это его глобальное свойство.
const TICK: Duration = Duration::from_millis(200);

/// Через сколько проверка микрофона выключается сама.
const MONITOR_TIMEOUT: Duration = Duration::from_secs(60);

/// Эпоха проверки микрофона: растёт на каждую команду `Ctl::Monitor`,
/// применённую в `drain_ctl`, независимо от того, поменялось ли состояние.
///
/// Нужна из-за гонки между командой и событием: `set_monitor` в `main.rs`
/// отвечает окну сразу, до того как аудио-поток разобрал канал (см. докблок
/// `drain_ctl`), поэтому событие `levels`, отправленное ДО обработки команды,
/// может прийти УЖЕ ПОСЛЕ ответа на неё и нести устаревшее `monitoring`.
/// Таймеры здесь не годятся — на медленной машине они разъедутся. Эпоха
/// решает это без времени: `main.rs` возвращает окну номер эпохи, который
/// получится после применения его команды, `levels` несёт номер эпохи, с
/// которой он посчитан, а окно верит полю `monitoring` только у событий с
/// эпохой не меньше последней своей.
///
/// `Arc<AtomicU64>`, а не поле `App`: счётчик должен быть виден и потоку
/// команд Tauri (чтобы `set_monitor` мог прочитать его синхронно), и аудио-
/// потоку (чтобы `drain_ctl` мог его увеличить) — а `App` целиком живёт
/// только внутри аудио-потока (см. докблок модуля).
pub type MonitorEpoch = Arc<AtomicU64>;

/// Команда аудио-потоку.
///
/// Шире, чем `Event` из ядра, намеренно: `Toggle` и `Shutdown` — это вопросы к
/// текущему состоянию машины, а не события в ней. Ответить на них может только
/// тот, кто состояние знает, то есть сам аудио-цикл; в `enum Event` их места
/// нет, и добавлять его туда — значит менять готовое ядро ради удобства GUI.
pub enum Ctl {
    /// Однозначное событие: ответ на вопрос, старт, стоп.
    Event(Event),
    /// «Переключи»: хоткей и пункт трея не знают, что сейчас происходит, и знать
    /// не должны. Решение принимается здесь, по настоящему состоянию машины —
    /// иначе пришлось бы держать копию состояния в UI и ловить рассинхрон.
    Toggle,
    /// Сменить микрофон. Вступает в силу со следующего открытия потоков —
    /// менять устройство под идущей записью значило бы порвать дорожку.
    SetMicDevice(DeviceChoice),
    /// Включить/выключить проверку микрофона. Как и `SetMicDevice`, это не
    /// событие машины: состояние записи от проверки не меняется.
    Monitor(bool),
    /// «Зайти и записать» во всплывашке встречи или в меню иконки. Для
    /// машины это `ManualStart`, но запись дополнительно останавливается по
    /// концу звонка — см. [`MeetingWatch`].
    JoinMeeting,
    /// Выключить/включить микрофон в идущей записи (кнопка в окне). Не
    /// событие машины: запись от этого не начинается и не кончается.
    SetMicMuted(bool),
    /// То же переключателем — для трея, который состояния не знает (тот же
    /// довод, что у [`Ctl::Toggle`]).
    ToggleMicMuted,
    /// На вопрос «вы говорите?» ответили «нет» (смахнули плашку): не
    /// спрашивать подольше.
    DeclineUnmuteQuestion,
    /// Выход. Обязан пройти через машину: см. [`run`].
    Shutdown,
}

/// Состояние в терминах UI: три ответа на вопрос «горит ли индикатор и пишем ли
/// мы». `Trigger` наружу не выносится — пользователю всё равно, чем запущена
/// запись, а `Finalizing` живёт доли секунды.
#[derive(Serialize, Clone, Copy, PartialEq, Eq, Debug, Default)]
#[serde(rename_all = "lowercase")]
pub enum UiState {
    #[default]
    Idle,
    Armed,
    Recording,
}

impl UiState {
    fn of(s: State) -> Self {
        match s {
            State::Idle => UiState::Idle,
            State::Armed => UiState::Armed,
            State::Recording(_) => UiState::Recording,
            // Finalizing — миг между стопом и Idle. Для UI это уже «не пишем»:
            // отдельная лампочка на 200 мс только моргала бы впустую.
            State::Finalizing => UiState::Idle,
        }
    }
}

/// Событие в машину + рассказать UI об ошибке.
///
/// Ошибка НЕ выходит наверх по `?` и не роняет цикл. В консольном бинаре ранний
/// выход ронял процесс — громко и заметно. Здесь ронять нечего: GUI переживёт
/// ошибку и будет выглядеть живым, ничего не записывая. Поэтому причина уходит
/// в UI событием, а цикл продолжает крутиться — ядро на ошибке уже свело машину
/// с миром (`App::on_event` сбрасывает в Idle), так что следующая встреча
/// начнётся с чистого листа.
fn feed(app: &mut App, handle: &AppHandle, e: Event, source: Option<&MicSession>) {
    if let Err(err) = app.on_event(e, source) {
        let _ = handle.emit("error", err.to_string());
        eprintln!("ошибка обработки {e:?}: {err}");
    }
}

/// Показать вопрос «записать?»: событие в главное окно, тост и всплывашка.
///
/// Тост и всплывашка вместе, а не по отдельности: кнопок «Записать»/«Нет» в
/// тосте не будет. `tauri-plugin-notification` 2.3 на десктопе кладёт в
/// `notify-rust` только title/body/icon/sound — `actions` он не прокидывает
/// вовсе (сам notify-rust кнопки на Windows умеет, плагин их не отдаёт).
/// Поэтому тост здесь — это «обрати внимание», а отвечают во всплывашке, где
/// кнопки настоящие.
///
/// Обратное тоже верно, поэтому тост и остался: всплывашку видно не всегда —
/// полноэкранный режим и второй монитор её съедают, а Windows вдобавок глушит
/// сам тост в полноэкранном режиме (Focus Assist). Два ненадёжных канала с
/// разными слепыми зонами надёжнее одного.
///
/// Главное окно НЕ разворачивается: раньше здесь были `unminimize`/`show`/
/// `set_focus`, и окно 460×640 вылезало в лицо с отъёмом фокуса ровно в
/// секунду, когда человек начинает говорить. Событие `ask` в webview уходит
/// по-прежнему — окно, если оно открыто, показывает тот же вопрос у себя.
fn ask(handle: &AppHandle, source: &str) {
    let _ = handle.emit("ask", source);

    let _ = handle
        .notification()
        .builder()
        .title("Записать встречу?")
        .body(format!("{source} — ответьте в окне приложения."))
        .show();

    show_ask_popup(handle, CLASSIC);
}

/// Тот же вопрос, но про встречу из календаря: детектор услышал звонок во
/// время встречи, по которой ещё не отказывались. Главное окно получает
/// обычное `ask` (строка взвода «Похоже, встреча в Zoom»), тост тот же, а
/// всплывашка — календарная, с названием встречи и кнопкой «Записать».
///
/// `emit_to("main")`, а не `emit`: окно `ask` на `ask` нарисовало бы старую
/// плашку и тут же перерисовало бы её календарной.
fn ask_calendar(handle: &AppHandle, source: &str, popup: &crate::calendar::planner::PopupPayload) {
    let _ = handle.emit_to("main", "ask", source);
    let _ = handle
        .notification()
        .builder()
        .title("Записать встречу?")
        .body(format!("{source} — ответьте в окне приложения."))
        .show();
    show_calendar_popup(handle, popup);
}

/// Показать плашку встречи (оба режима). Зовут тикер календаря и
/// [`ask_calendar`].
pub fn show_calendar_popup(handle: &AppHandle, popup: &crate::calendar::planner::PopupPayload) {
    let _ = handle.emit_to("ask", "calendar", popup);
    show_ask_popup(handle, CALENDAR);
}

/// Меню ⋯ во всплывашке (путь B): окно вырастает вниз на время, пока меню
/// открыто, и возвращается обратно. Позиция возвращается следом за размером.
#[tauri::command]
pub fn ask_menu(open: bool, app: AppHandle) -> Result<(), String> {
    let w = app.get_webview_window("ask").ok_or("окна ask нет")?;
    // Скрытое окно не трогаем: запоздалый вызов не должен менять размер
    // следующей (например, классической) плашки.
    if !w.is_visible().unwrap_or(false) {
        return Ok(());
    }
    let h = if open { CAL_ASK_HEIGHT + ASK_MENU_EXTRA } else { CAL_ASK_HEIGHT };
    w.set_size(LogicalSize::new(ASK_WINDOW_WIDTH, h)).map_err(|e| e.to_string())?;
    if let Some((x, y)) = *ASK_ORIGIN.lock().unwrap_or_else(|e| e.into_inner()) {
        let _ = w.set_position(LogicalPosition::new(x, y));
    }
    Ok(())
}

/// Спросить «вы говорите? микрофон выключен» — той же всплывашкой, что и
/// «записать встречу?».
///
/// Именно ею, а не тостом и не главным окном, потому что человек в этот
/// момент может смотреть на другой экран: всплывашка встаёт на тот монитор,
