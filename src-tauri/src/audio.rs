pub const CAL_ASK_WIDTH: f64 = 440.0;

/// Окно под календарную плашку выше: название встречи бывает в две строки.
pub const CAL_ASK_HEIGHT: f64 = 108.0;

/// Насколько окно растёт, пока открыто меню ⋯ (путь B, задача 1 плана):
/// меню рисуется в HTML под плашкой. Постоянно высокое окно не годится —
/// прозрачная часть окна перехватывает клики (`setIgnoresMouseEvents: false`
/// в `показать_поверх`), а живёт календарная плашка до трёх минут.
pub const ASK_MENU_EXTRA: f64 = 48.0;

#[derive(Clone, Copy)]
struct Geometry {
    card_width: f64,
    height: f64,
}

const CLASSIC: Geometry = Geometry { card_width: ASK_WIDTH, height: ASK_HEIGHT };
const CALENDAR: Geometry = Geometry { card_width: CAL_ASK_WIDTH, height: CAL_ASK_HEIGHT };

/// Левый верхний угол окна `ask` в последнем показе, в логических точках.
/// Нужен `ask_menu`: смена высоты на macOS держит НИЖНИЙ край окна, и
/// без возврата позиции плашка уехала бы вверх.
static ASK_ORIGIN: Mutex<Option<(f64, f64)>> = Mutex::new(None);

/// Показать всплывашку у верхнего правого угла экрана.
///
/// **Фокус не забирается — главное свойство этого окна.** Вопрос приходит
/// ровно тогда, когда человек начал говорить в звонке; окно, ставшее в этот
/// момент ключевым, увело бы клавиатуру из звонилки. Держится это на
/// `focusable: false` в конфиге.
///
/// **`alwaysOnTop` здесь намеренно НЕ включён**, хотя просится. Приложение
/// живёт в строке меню (`ActivationPolicy::Accessory`) и активным не бывает
/// никогда, а окна плавающего уровня у неактивного приложения macOS не
/// показывает вовсе: окно существует, `is_visible()` отвечает `true`, а на
/// экране его нет — проверено перебором настроек. Вместо уровня работает
/// `show()`: он поднимает окно над чужими в момент появления, а живёт вопрос
/// семь секунд.
///
/// Позиция считается тут, а не задаётся в конфиге числом: «правый верхний
/// угол» — функция от разрешения монитора. Берётся `work_area`, а не `size`:
/// иначе всплывашка залезла бы под строку меню и под док.
fn show_ask_popup(handle: &AppHandle, g: Geometry) {
    let Some(w) = handle.get_webview_window("ask") else {
        // Единственная причина — окно не объявлено в конфиге. Вопрос при этом
        // уже ушёл и в webview, и в системный тост, так что ответить есть где;
        // молчать всё же нельзя — иначе всплывашка «просто не появляется».
        eprintln!("окно всплывашки «ask» не найдено — вопрос только в тосте и в главном окне");
        return;
    };

    // Монитор — тот, где сейчас мышь, а НЕ главный. У человека с двумя экранами
    // главный — ноутбук, а работает он во внешнем: вопрос, вылезший на другом
    // экране, ничем не отличается от вопроса, не вылезшего вовсе.
    let монитор = handle
        .cursor_position()
        .ok()
        .and_then(|p| w.monitor_from_point(p.x, p.y).ok().flatten())
        .or_else(|| w.primary_monitor().ok().flatten());

    let Some(m) = монитор else {
        #[cfg(target_os = "macos")]
        {
            let h = handle.clone();
            let _ = handle.run_on_main_thread(move || показать_поверх(&h));
        }
        #[cfg(not(target_os = "macos"))]
        показать_обычным_окном(&w);
        return;
    };

    // Считаем в ЛОГИЧЕСКИХ точках, и это не вкусовщина. Общая система координат
    // у экранов macOS — точки: у каждого экрана свой масштаб, и «физические
    // пиксели» разных экранов между собой несравнимы вообще. Позиция,
    // посчитанная в них, уезжает мимо всех экранов сразу — окно при этом
    // остаётся «видимым», просто нигде.
    let масштаб = m.scale_factor();
    let область = m.work_area();
    let слева = область.position.x as f64 / масштаб;
    let ширина = область.size.width as f64 / масштаб;
    let сверху = область.position.y as f64 / масштаб;
    let x = слева + ширина - g.card_width - ASK_RIGHT_MARGIN;
    let y = сверху + ASK_TOP_MARGIN;

    // Окно левее плашки на поле под тень: к правому краю экрана прижимается
    // плашка, а не граница окна.
    let _ = w.set_size(LogicalSize::new(ASK_WINDOW_WIDTH, g.height));
    let _ = w.set_position(LogicalPosition::new(x - ASK_LEFT_GUTTER, y));
    *ASK_ORIGIN.lock().unwrap_or_else(|e| e.into_inner()) = Some((x - ASK_LEFT_GUTTER, y));
    #[cfg(target_os = "macos")]
    {
        let h = handle.clone();
        let _ = handle.run_on_main_thread(move || показать_поверх(&h));
    }
    #[cfg(not(target_os = "macos"))]
    показать_обычным_окном(&w);
    следить_за_наведением(handle, (x, y, g.card_width, g.height), масштаб);
    log::info!(
        "всплывашка: экран {:?}, плашка в ({x:.0}, {y:.0})",
        m.name()
    );
}

/// Поднять окно поверх остальных, ничего не активируя, и объявить, как оно
/// живёт относительно рабочих столов.
///
/// **Окно превращается в `NSPanel`.** Это главное здесь. Приложение живёт в
/// строке меню (`ActivationPolicy::Accessory`) и активным не бывает никогда, а
/// обычному `NSWindow` неактивного приложения macOS отказывает и в плавающем
/// уровне (окно есть, `is_visible()` отвечает `true`, на экране пусто), и в
/// показе поверх чужого полноэкранного окна: вместо плашки система уносит
/// человека на тот рабочий стол, где окно живёт. `NSPanel` — тот же `NSWindow`
/// с другим поведением у оконного сервера; на нём и уровень, и полноэкранный
/// сосед работают. Так сделаны Spotlight, Raycast и всплывашка Zoom, и так же
/// это решает плагин `tauri-nspanel` (в зависимости не берём: он не издан на
/// crates.io, тянется из git и весь состоит из макросов, а нужны нам ровно
/// шесть вызовов).
///
/// Класс подменяется на живом окне (`object_setClass`) — Tauri создаёт окно
/// сам и класс выбрать не даёт. Подмена разовая и в одну сторону: `NSPanel`
/// не добавляет к `NSWindow` ни одного поля, то есть новый класс не длиннее
/// старого и за чужую память не залезает. Взамен теряются надстройки tao над
/// `NSWindow` — `canBecomeKeyWindow` из `focusable: false` и перехват
/// `sendEvent:` для перетаскивания за фон. Первое заменяет
/// `becomesKeyOnlyIfNeeded`, второе всплывашке не нужно: её не таскают.
///
/// Дальше по мелочи, и каждое — не украшение:
///
/// - `NSWindowStyleMaskNonactivatingPanel` — панель принимает мышь, не делая
///   приложение активным. Без него клик по «Записать» уводит фокус из звонка.
/// - `becomesKeyOnlyIfNeeded` — клавиатуру панель забирает, только если её
///   попросит поле ввода. Полей тут нет, значит никогда.
/// - `orderFrontRegardless` вместо `orderFront:` — «подними, даже если
///   приложение неактивно». Ровно наш случай; обычный `orderFront:` у
///   неактивного приложения молча ничего не делает.
/// - `CanJoinAllSpaces | FullScreenAuxiliary` — жить на всех рабочих столах и
///   показываться поверх полноэкранных программ. Без второго флага macOS
///   вместо показа переключает рабочий стол.
///
/// `show()` в tao для этого не годится: это `makeKeyAndOrderFront`, а он и
/// фокус забирает, и на «свой» рабочий стол утаскивает.
///
/// Зовётся только с главного потока: AppKit на такие вызовы из чужого потока
/// не ругается, а убивает процесс («Must only be used from the main thread»).
#[cfg(target_os = "macos")]
fn показать_поверх(handle: &AppHandle) {
    use objc2::runtime::{AnyClass, AnyObject};

    // Значения из заголовков AppKit (сверено с объявлениями objc2-app-kit
    // 0.3.2, файл `generated/NSWindow.rs`):
    //   NSWindowStyleMaskNonactivatingPanel            = 1 << 7
    //   NSWindowCollectionBehaviorCanJoinAllSpaces     = 1 << 0
    //   NSWindowCollectionBehaviorFullScreenAuxiliary  = 1 << 8
    //   NSFloatingWindowLevel                          = 3
    //
    // `Stationary` (1 << 4) сюда добавлять нельзя: проверено перебором, с ним
    // окно не показывается вовсе. Уровень взят плавающий, а не `Status` (25):
    // 25 — это выше строки меню, и плашка налезала бы на неё.
    const НЕАКТИВИРУЮЩАЯ_ПАНЕЛЬ: usize = 1 << 7;
    const ПОВЕДЕНИЕ: usize = (1 << 0) | (1 << 8);
    const УРОВЕНЬ: isize = 3;

    let Some(w) = handle.get_webview_window("ask") else {
        return;
    };
    let Ok(указатель) = w.ns_window() else {
        return;
    };
    if указатель.is_null() {
        return;
    }
    // Безопасность: указатель отдан самим tao и живёт столько же, сколько окно,
    // а окно живёт до конца процесса — оно объявлено в конфиге и не
    // уничтожается. Поток — главный, это обеспечивает вызывающий.
    unsafe {
        let окно = указатель as *mut AnyObject;

        // Функции рантайма Objective-C напрямую: `AnyObject::set_class` из
        // objc2 в отладочной сборке падает на проверке «размеры классов
        // совпадают», а они и не совпадают — `TaoWindow` длиннее `NSPanel` на
        // одно поле. Уменьшение размера безопасно (за чужую память не лезем),
        // но проверке этого не объяснить.
        extern "C" {
            fn object_getClass(obj: *mut AnyObject) -> *const AnyClass;
            fn object_setClass(obj: *mut AnyObject, cls: *const AnyClass) -> *const AnyClass;
        }

        let панель: *const AnyClass = objc2::class!(NSPanel);
        if object_getClass(окно) != панель {
            object_setClass(окно, панель);
            let _: () = objc2::msg_send![окно, setStyleMask: НЕАКТИВИРУЮЩАЯ_ПАНЕЛЬ];
            let _: () = objc2::msg_send![окно, setFloatingPanel: true];
            let _: () = objc2::msg_send![окно, setBecomesKeyOnlyIfNeeded: true];
            let _: () = objc2::msg_send![окно, setHidesOnDeactivate: false];
            let _: () = objc2::msg_send![окно, setLevel: УРОВЕНЬ];
            log::info!("всплывашка: окно стало NSPanel");
        }

        let _: () = objc2::msg_send![окно, setCollectionBehavior: ПОВЕДЕНИЕ];
        let _: () = objc2::msg_send![окно, setAcceptsMouseMovedEvents: true];
        let _: () = objc2::msg_send![окно, setIgnoresMouseEvents: false];
        let _: () = objc2::msg_send![окно, orderFrontRegardless];
    }
}

/// Показать всплывашку на системах, где обычному окну не отказывают в верхнем
/// уровне.
///
/// На macOS так нельзя, и причина в докблоке `show_ask_popup`: приложение
/// живёт в строке меню как `Accessory`, а окна плавающего уровня у неактивного
/// приложения система не показывает вовсе. На Windows этой беды нет — там это
/// обычный `HWND_TOPMOST`, и без него плашка вылезает ПОД окном звонка, то
/// есть не вылезает.
#[cfg(not(target_os = "macos"))]
fn показать_обычным_окном(w: &tauri::WebviewWindow) {
    let _ = w.set_always_on_top(true);
    let _ = w.show();
}

/// Как часто спрашиваем, где мышь, пока висит всплывашка.
///
/// 50 мс — это 20 раз в секунду. Меньше не нужно: событие тут одно —
/// «навёл/увёл», и задержка в полкадра на нём не читается. Больше — лишняя
/// работа в фоне у программы, которая должна быть незаметной.
const ASK_HOVER_INTERVAL: Duration = Duration::from_millis(50);

/// Сколько сторож живёт максимум. Всплывашка живёт 7 секунд (полоска в
/// `ui/ask.html`); запас — на случай, если окно почему-то не спряталось.
const ASK_HOVER_MAX: Duration = Duration::from_secs(15);

/// Номер текущего показа. Каждый показ увеличивает счётчик, и сторож прошлого
/// показа, увидев чужой номер, молча уходит: два сторожа на одно окно слали бы
/// «навёл» и «увёл» вперемешку.
static ПОКОЛЕНИЕ_ВСПЛЫВАШКИ: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

/// Следить, стоит ли мышь на плашке, и говорить об этом окну.
///
/// **Почему не CSS `:hover`.** Окно принадлежит неактивному приложению, а
/// таким окнам macOS движений мыши не шлёт вовсе — вебвью о наведении не
/// узнаёт, и `:hover` не срабатывает никогда. У Tauri своего пути для этого
/// нет (tauri-apps/tauri#11386 — открытая просьба), поэтому наведение считает
/// Rust по положению курсора, а вебвью получает готовое событие `hover`.
///
/// **Рамка — плашки, а не окна.** Окно шире плашки на запас справа, чтобы
/// смахивание не обрезалось краем; мышь в этом запасе — это мышь над пустым
/// местом, и отсчёт она останавливать не должна.
///
/// Координаты физические: `cursor_position` у Tauri отдаёт их в той же системе,
/// что и позиция монитора, а плашка посчитана в логических точках — отсюда
/// умножение на масштаб.
fn следить_за_наведением(handle: &AppHandle, плашка: (f64, f64, f64, f64), масштаб: f64) {
    use std::sync::atomic::Ordering;

    let (лx, лy, лш, лв) = плашка;
    let (x0, y0) = (лx * масштаб, лy * масштаб);
    let (x1, y1) = (x0 + лш * масштаб, y0 + лв * масштаб);

    let моё = ПОКОЛЕНИЕ_ВСПЛЫВАШКИ.fetch_add(1, Ordering::SeqCst) + 1;
    let h = handle.clone();
    std::thread::spawn(move || {
        let начало = Instant::now();
        // Стартовое состояние — «не наведено», и первое же событие уйдёт,
        // только если мышь и правда на плашке: вопрос приходит сам, курсор в
        // этот момент почти всегда в другом месте.
        let mut было = false;
        // Пока окно не показалось, «невидимо» — это ещё не «спрятали»:
        // `orderFrontRegardless` уезжает на главный поток и случается позже
        // нашего первого круга.
        let mut показалось = false;
        loop {
            std::thread::sleep(ASK_HOVER_INTERVAL);
            if ПОКОЛЕНИЕ_ВСПЛЫВАШКИ.load(Ordering::SeqCst) != моё {
                return;
            }
            if начало.elapsed() > ASK_HOVER_MAX {
                return;
            }
            let Some(w) = h.get_webview_window("ask") else {
                return;
            };
            match w.is_visible() {
                Ok(true) => показалось = true,
                // Плашка уехала — сторожить больше нечего.
                Ok(false) if показалось => return,
                _ => continue,
            }
            let наведено = h
                .cursor_position()
                .map(|p| p.x >= x0 && p.x <= x1 && p.y >= y0 && p.y <= y1)
                .unwrap_or(false);
            if наведено != было {
                было = наведено;
                log::debug!("всплывашка: наведение {наведено}");
                let _ = w.emit("hover", наведено);
            }
        }
    });
}

/// Убрать всплывашку.
///
/// Зовётся из [`sync`] на любом уходе из `Armed`: ответить можно не только в
/// ней (главное окно, трей, хоткей), и вопрос, переживший свой ответ, — это
/// кнопка «Записать», которая уже ничего не начнёт.
pub(crate) fn hide_ask_popup(handle: &AppHandle) {
    if let Some(w) = handle.get_webview_window("ask") {
        let _ = w.hide();
        // Меню ⋯ могло оставить окно высоким: следующий показ задаёт размер сам,
        // но возвращаем и здесь, чтобы закрытие не зависело от JS.
        let _ = w.set_size(LogicalSize::new(ASK_WINDOW_WIDTH, CAL_ASK_HEIGHT));
    }
    crate::calendar::popup_gone(handle);
}

/// Микрофон сменился посреди записи (или проверки) — событие `mic-switched`
/// `{ name }`: имя выбранного устройства из конфига, `null` — «как в системе».
/// Аудио-поток знает только идентификатор, имя есть у конфига.
fn emit_mic_switched(handle: &AppHandle) {
    let name = crate::config::Config::load(handle).mic_device_name;
    let _ = handle.emit("mic-switched", serde_json::json!({ "name": name }));
}

/// Записать состояние в [`Status`] и разослать, если оно изменилось.
///
/// Только на изменении: цикл крутится 5 раз в секунду, и слать одно и то же в
/// webview и в трей — это шум на ровном месте. «Изменилось ли» спрашивается у
/// самого `Status`, а не у локальной копии: копия рядом с истиной — это второй
/// источник правды, который однажды разъедется с первым.
///
/// Запись в `Status` идёт ПЕРЕД `emit` намеренно: кто спросит `get_state` в
/// промежутке, получит новое состояние, а следом ещё и событие о нём —
/// повторение безвредно, а вот обратный порядок дал бы окно, в котором событие
/// уже ушло, а спросивший получил бы старое.
fn sync(handle: &AppHandle, app: &App, status: &Status) {
    let now = UiState::of(app.state());
    if status.set_state(now) {
        let _ = handle.emit("state", now);
        tray::set_state(handle, now);
        // Меню иконки и всплывашка встречи зависят от того, идёт ли запись:
        // тикер календаря пересчитывает их сразу, а не через 15 секунд.
        crate::calendar::wake(handle);
        // Всплывашка живёт ровно столько же, сколько сам вопрос, то есть пока
        // машина в `Armed`. См. [`hide_ask_popup`].
        if now != UiState::Armed {
            hide_ask_popup(handle);
        }
    }

    // Наверх идёт ИДЕНТИФИКАТОР эндпоинта: аудио-поток знает только его.
    // Человеческое имя подставляет тот, у кого есть конфиг, — окно (для баннера)
    // и код ниже (для тоста, который до окна не доходит).
    let warn = app.device_warning();
    if status.set_device_warning(warn.as_deref()) {
        let _ = handle.emit("device-warning", warn.clone());
        if let Some(id) = warn {
            // Тост показывается и при закрытом окне, поэтому имя ему нужно
            // здесь; конфиг читается только в момент изменения, а не каждый тик.
            let имя = crate::config::Config::load(handle)
                .mic_device_name
                .unwrap_or(id);
            let _ = handle
                .notification()
                .builder()
                .title(format!("Микрофон «{имя}» недоступен"))
                .body(
                    "Пишется тот, что выбран в системе. Проверьте, подключён ли \
                     он, или выберите другой в настройках.",
                )
                .show();
        }
    }

    // Тоста здесь нет намеренно: это не беда, а объяснение, и нужно оно ровно
    // тому, кто прямо сейчас смотрит в выпадашку. Всплывашка поверх экрана
    // посреди встречи была бы дороже пользы.
    if status.set_mic_deferred(app.mic_change_deferred()) {
        let _ = handle.emit("mic-deferred", app.mic_change_deferred());
    }

    // Отсюда, а не из обработчика команды: выключение снимается и само — с
    // концом записи (см. `App::set_mic_muted`), и об этом окну и трею тоже
    // надо узнать.
    if status.set_mic_muted(app.is_mic_muted()) {
        let _ = handle.emit("mic-muted", app.is_mic_muted());
        tray::set_mic_muted(handle, app.is_mic_muted());
        // Микрофон включили — из окна, из трея или из самой плашки: вопрос
        // «вы говорите?» на экране больше ни о чём. В записи плашка другого
        // вопроса висеть не может (тот живёт только в `Armed`).
        if !app.is_mic_muted() {
            hide_ask_popup(handle);
        }
    }

    // Без `emit`: никто не подписан на «какая запись сейчас пишется» —
    // список читает её через снимок в момент своего собственного вызова
    // (`list_recordings`, `delete_recording`, автоочистка), а не заранее.
    // Событие здесь дублировало бы то, что и так приходит на каждый тик
    // через уже существующее событие `state`.
    status.set_current_recording(app.current_recording());
}

/// Решение по одной команде: какое событие уходит в машину и надо ли после этого
/// выходить. `None` — команда не событие машины вовсе.
///
/// Чистая функция по образцу `poll_to_event`, и ровно по той же причине: решение
/// «`Shutdown` → `ManualStop`» — это инвариант 6 («выход из трея финализирует
/// запись») в чистом виде, и жить оно должно там, где его можно прочитать
/// тестом, а не внутри `loop`, до которого тест не дотянется.
///
/// `SetMicDevice`/`Monitor` дают `None`, а не `unreachable!()`. `drain_ctl`
/// перехватывает оба варианта раньше и сюда их не пропускает, поэтому на
/// практике эта ветка не исполняется, но паника здесь была бы неверной ценой
/// за это предположение: она убивает единственный поток, который умеет писать
/// на диск, причём тихо — `status::fatal` от паники в этом потоке не
/// срабатывает, а «поток мёртв» всплывает только на следующей команде из GUI.
/// `None` несёт тот же факт «сюда дойти не должны», но не обрушивает поток,
/// если предположение всё же окажется неверным (например, после будущей
/// правки, убравшей перехват в `drain_ctl`).
fn ctl_to_event(c: &Ctl, s: State) -> Option<(Event, bool)> {
    match c {
        Ctl::Event(e) => Some((*e, false)),
        // В Armed ManualStart — это подтверждение (кольцо уезжает в файл), в
        // Idle — старт с нуля, в записи — стоп. Решает машина, мы только
        // выбираем событие по её состоянию.
        Ctl::Toggle => Some(match s {
            State::Recording(_) => (Event::ManualStop, false),
            _ => (Event::ManualStart, false),
        }),
        // Не Toggle: если запись уже идёт, «Зайти и записать» её не гасит.
        Ctl::JoinMeeting => Some((Event::ManualStart, false)),
        // Выход обязан пройти через машину, а не через process::exit: ManualStop
        // закроет и финализирует файл, если запись идёт. hound пишет длину данных
        // в заголовок только на finalize(); убить процесс во время записи — это
        // WAV, который существует, открывается и играет тишину.
        //
        // В Armed это тоже верно: там ManualStop = DiscardRing, то есть кольцо
        // выброшено и микрофон отпущен.
        Ctl::Shutdown => Some((Event::ManualStop, true)),
        // Не событие машины (см. `Ctl::SetMicDevice`): `drain_ctl` перехватывает
        // этот вариант ДО вызова `ctl_to_event` и сюда его не пропускает.
        Ctl::SetMicDevice(_) => None,
        // Тот же случай, что у `SetMicDevice`: `drain_ctl` перехватывает
        // `Monitor` раньше, чем дело доходит сюда.
        Ctl::Monitor(_) => None,
        // И выключение микрофона: `drain_ctl` применяет его сам.
        Ctl::SetMicMuted(_) | Ctl::ToggleMicMuted | Ctl::DeclineUnmuteQuestion => None,
    }
}

/// Разобрать всё, что накопилось в канале. `true` — пришёл `Shutdown`, цикл
/// обязан закончиться.
///
/// Отделено от [`run`] не ради красоты. `ctl_to_event` сама по себе инварианта 6
/// не доказывает: она может честно вернуть `ManualStop`, а вызывающий — забыть
/// его скормить и выйти сразу. Это ровно та бага «в проводке», о которой
/// предупреждает докблок `poll_to_event`: хелпер покрыт, проводка нет. Поэтому
/// `feed` здесь — параметр: тест подставляет свой и смотрит, что именно уехало в
/// машину и в каком порядке относительно выхода.
///
/// Отказ проверки обязан дойти до окна, а не только в stderr: в релизе консоли
/// нет, и молчаливый отказ выглядел бы как «нажал Проверить, полоска стоит» —
/// то есть неотличимо от «микрофон не слышит», ровно того, что эта кнопка и
/// должна различать. Но сам `drain_ctl` не знает про `AppHandle` (и не должен:
/// на нём держатся тесты проводки без Tauri), поэтому канал ошибки приходит
/// параметром.
///
/// `epoch` растёт на КАЖДУЮ применённую `Ctl::Monitor`, включая ту, что не
/// изменила состояние (например, второй `Monitor(true)` подряд) — см.
/// докблок [`MonitorEpoch`]. Рост именно здесь, а не в `App::set_monitor`:
/// эпоха — свойство проводки команд, а не проверки микрофона как таковой, и
/// `App` о ней вообще не должен знать.
///
/// `watch` — слежка «Зайти и записать» (см. [`MeetingWatch`]): заводится здесь,
/// потому что только здесь видно, куда `JoinMeeting` перевёл машину.
fn drain_ctl(
    app: &mut App,
    rx: &Receiver<Ctl>,
    active: Option<&MicSession>,
    epoch: &AtomicU64,
    watch: &mut MeetingWatch,
    mut feed: impl FnMut(&mut App, Event, Option<&MicSession>),
    mut on_error: impl FnMut(String),
) -> bool {
    for c in rx.try_iter() {
        // Не события машины: состояние записи от них не меняется.
        if let Ctl::SetMicDevice(choice) = c {
            app.set_mic_device(choice);
            continue;
        }
        if let Ctl::Monitor(on) = c {
            epoch.fetch_add(1, Ordering::SeqCst);
            if let Err(e) = app.set_monitor(on) {
                on_error(format!("проверка микрофона: {e}"));
            }
            continue;
        }
        // Вне записи `set_mic_muted` команду не применяет — это не ошибка, а
        // кнопка, нажатая на последней секунде встречи: сказать человеку
        // нечего, окно и трей сами увидят, что записи больше нет.
        if let Ctl::SetMicMuted(on) = c {
            app.set_mic_muted(on);
            continue;
        }
        if let Ctl::ToggleMicMuted = c {
            app.set_mic_muted(!app.is_mic_muted());
            continue;
        }
        if let Ctl::DeclineUnmuteQuestion = c {
            app.decline_unmute_question();
            continue;
        }
        // `None` здесь означает «команда не должна была сюда дойти» (см.
        // докблок `ctl_to_event`) — а не «ничего не делать» через панику.
        // `SetMicDevice`/`Monitor` перехвачены веткой выше, так что на
        // практике сюда попадают только команды с `Some`.
        let Some((e, quit)) = ctl_to_event(&c, app.state()) else {
            continue;
        };
        // На выходе источник не нужен: ManualStop закрывает то, что уже пишется,
        // а не начинает новое.
        let before = app.state();
        feed(app, e, if quit { None } else { active });
        // «Остановить», хоткей, новый ручной старт, выход — решение человека,
        // а не звонилки: слежка «Зайти и записать» после них снята.
        if matches!(c, Ctl::JoinMeeting) {
            if starts_watch(before, app.state()) {
                watch.start();
            }
        } else if matches!(
            c,
            Ctl::Toggle | Ctl::Shutdown | Ctl::Event(Event::ManualStart | Event::ManualStop)
        ) {
            watch.reset();
        }
        if quit {
            return true;
        }
    }
    false
}

/// Решение «слать ли `levels` в этом тике».
///
/// Без простоя было бы 5 событий в секунду в пустоту, поэтому в тишине (не
/// проверяем и не пишем) событие не шлётся. Но `was_monitoring` — отдельный
/// параметр, а не то же самое, что `is_monitoring`, и вот почему: за один тик
/// проверка может успеть выключиться — командой `Ctl::Monitor(false)` в
/// `drain_ctl`, автовыключением по таймауту или концом записи (`Action::
/// CloseFile` в ядре гасит флаг проверки как побочный эффект), — и к моменту,
/// когда вызывающий спрашивает это условие, `is_monitoring()` уже вернёт
/// `false`, а `state()` уже может быть `Idle`. Без `was_monitoring` это
/// финальное «проверка кончилась» терялось бы навсегда: окно не получило бы
/// событие с `monitoring: false`, кнопка и полоски остались бы висеть в
/// состоянии «идёт проверка» до следующей настоящей записи.
///
/// `was_monitoring` — это `is_monitoring()`, снятый ДО обработки команд,
/// таймера и событий машины за этот тик (см. вызов в [`run`]), то есть «было
/// ли что послушать, когда тик начинался».
fn should_emit_levels(was_monitoring: bool, is_monitoring: bool, state: State) -> bool {
    was_monitoring || is_monitoring || state != State::Idle
}

/// Что нести в поле `mic`/`system` события `levels` на этом тике.
///
/// В `Idle` без проверки мерить нечего: потоки закрыты (см. докблок
/// `App::set_monitor`), а значит `l` — это не текущий уровень, а то, что
/// намерил последний тик перед выключением, затухающее по `LEVEL_DECAY`.
/// Показать его — соврать, что микрофон ещё слышен. Именно этот тик — тот, о
/// котором говорит докблок `should_emit_levels`: проверка ТОЛЬКО ЧТО
/// выключилась, и должна принести нули, а не последнее измеренное значение.
///
/// В любом другом случае (идёт проверка или идёт запись, `state != Idle`)
/// уровни настоящие, и трогать их незачем.
fn levels_to_emit(l: Levels, monitoring: bool, state: State) -> Levels {
    if !monitoring && state == State::Idle {
        Levels::default()
    } else {
        l
    }
}

/// Сколько опросов подряд чужого захвата микрофона может не быть, прежде чем
/// гейт признает звонок законченным. 30 × `POLL_INTERVAL` (2 с) = минута.
///
/// Терпение досталось от прежнего гейта по звуку и оставлено намеренно, хотя
/// паузы в разговоре новый сигнал не рвут: часть звонилок отпускает микрофон,
/// пока человек замьючен (так делает браузерный Meet, и ничто не мешает так
/// же повести себя очередной версии Discord или Slack). Гейт стоит на СПИСКЕ
/// сессий (см. `Detect::gate`), и без терпения один свободный опрос дал бы
/// `SessionGone`: в `Armed` выбросил бы кольцо, в `Recording(Auto)` закрыл бы
/// файл посреди встречи, а размьют прилетел бы новым «записать?».
///
/// Цена прежняя: конец звонка виден только по отпущенному микрофону
/// (Zoom/Teams/Slack остаются открытыми), поэтому автозапись переживает конец
/// встречи на эту минуту. Закрытие самой звонилки ждать не заставляет —
/// пустой список сессий проходит гейт насквозь, и `SessionGone` приходит
/// сразу. Ручной стоп работает всё это время как обычно.
#[cfg(target_os = "macos")]
const MAC_FREE_POLLS_BEFORE_DROP: u32 = 30;

/// Сколько опросов подряд чужой захват микрофона должен продержаться, чтобы
/// поднять вопрос «записать?». 4 опроса по [`POLL_INTERVAL`] (2 с) — это 6
/// секунд между первым и последним, то есть захват дольше пяти секунд.
///
/// Раньше разгон отсекал «дзинь» уведомлений при гейте по звуку. Уведомления
/// микрофон не берут, но короткие захваты при открытой звонилке бывают:
/// диктовка, голосовое сообщение, «проверить микрофон» в настройках самой
/// звонилки. Число оставлено прежним, чтобы взвод вёл себя так же, как до
/// смены сигнала.
///
/// Цена тоже прежняя: вопрос про настоящую встречу появляется на 6–8 с позже,
/// и ровно столько её начала не попадёт в предзапись — кольцо (и системный
/// тап) стартует с `Armed`, а `Armed` наступает после разгона.
///
/// Разгон нужен только на ВОСХОДЯЩЕМ фронте. Пока звонок уже идёт
/// (`was_active`), занятый микрофон проходит без счёта.
#[cfg(target_os = "macos")]
const MAC_BUSY_POLLS_BEFORE_ARM: u32 = 4;

/// Слежка за записью «Зайти и записать».
///
/// Такая запись стартует из простоя (`ManualStart` → `Recording(Manual)`):
/// звонилка в этот момент только открывается и микрофон ещё не заняла. Будь
/// запись авто, ей нечего было бы ждать; будь она просто ручной — она не
/// остановилась бы по концу звонка, как останавливается запись из «Записать?»
/// (`Recording(Auto)` + `SessionGone` в `src/session.rs`). Слежка даёт второе
/// без первого: конец звонка останавливает запись, только если детектор хоть
/// раз видел звонилку с занятым микрофоном после старта.
///
/// Звонок в браузере (Google Meet, Teams и Zoom в вебе) детектор не видит —
/// там запись так и остаётся ручной.
#[derive(Default, Debug, PartialEq, Eq)]
struct MeetingWatch {
    on: bool,
    seen_call: bool,
}

impl MeetingWatch {
    fn start(&mut self) {
        self.on = true;
        self.seen_call = false;
    }

    fn reset(&mut self) {
        *self = Self::default();
    }

    /// Один опрос детектора. `manual_recording` — машина в `Recording(Manual)`,
    /// `call_active` — после гейта есть активная сессия, `event` — что выдал
    /// `poll_to_event`. `true` — увиденный звонок кончился, пора `ManualStop`.
    fn step(&mut self, manual_recording: bool, call_active: bool, event: Option<Event>) -> bool {
        if !manual_recording {
            self.reset();
            return false;
        }
        if !self.on {
            return false;
        }
        if call_active {
            self.seen_call = true;
            return false;
        }
        if self.seen_call && event == Some(Event::SessionGone) {
            self.reset();
            return true;
        }
        false
    }
}

/// Заводить ли слежку после `JoinMeeting`. Только переход «простой → ручная
/// запись»: из взвода машина даёт `Recording(Auto)` и остановится сама, а
/// уже идущую ручную запись (начатую кнопкой) превращать в авто нельзя.
fn starts_watch(before: State, after: State) -> bool {
    before == State::Idle && after == State::Recording(Trigger::Manual)
}

/// Вся память детекта между опросами: «была ли сессия на прошлом опросе» и —
/// только на macOS — счётчики гейта.
///
/// Существует отдельной структурой не ради порядка, а потому, что здесь жила
/// ошибка, которую невозможно было увидеть тестом. `was_active` раньше был
/// локальной переменной цикла [`run`], и защёлкивался он ДО того, как
/// применялся гейт:
///
/// ```text
/// let (found, event) = poll_to_event(was_active, sessions, me);
/// was_active = active.is_some();        // защёлкнуто по НЕгейтованному опросу
/// if let Some(e) = event { if gate_ok { feed(...) } }   // гейт — на событии
/// ```
///
/// `poll_to_event` выдаёт `SessionAppeared` только на фронте «сессий не было →
/// сессия есть». Гейт на событии этот фронт не откладывал, а уничтожал: Zoom,
/// открытый в 09:00 без звонка, поднимал `was_active` в `true` навсегда, а
/// единственное `SessionAppeared` выбрасывалось гейтом. В 09:30 человек
/// заходил в настоящий звонок — и `poll_to_event(true, [zoom], me)` молчал до
/// самого закрытия Zoom.
///
/// Гейт принадлежит ВХОДУ `poll_to_event`, а не его выходу. Отсюда и форма
/// этого типа: `was_active` — поле, которое обновляется в том же месте, где
/// применяется гейт, — [`Detect::step`]. Разъехаться им негде, а тест может
/// прогнать хоть сто опросов подряд без Tauri, детектора и Core Audio.
#[derive(Default)]
struct Detect {
    was_active: bool,
    /// Сколько опросов подряд идущий звонок живёт без чужого захвата
    /// микрофона — см. [`MAC_FREE_POLLS_BEFORE_DROP`].
    #[cfg(target_os = "macos")]
    free_polls: u32,
    /// Сколько опросов подряд чужой захват уже держится на восходящем фронте —
    /// см. [`MAC_BUSY_POLLS_BEFORE_ARM`].
    #[cfg(target_os = "macos")]
    busy_polls: u32,
}

impl Detect {
    /// Решение по одному опросу детектора: кто теперь активная сессия и какое
    /// событие из этого следует. Вся межопросная память — внутри.
    ///
    /// `mic_busy` — держит ли микрофон какой-нибудь процесс, кроме нас
    /// (`MacDetector::mic_in_use_by_others`). На Windows не используется.
    fn step(
        &mut self,
        sessions: Vec<MicSession>,
        mic_busy: bool,
        me: u32,
    ) -> (Option<MicSession>, Option<Event>) {
        // Гейт — ДО `poll_to_event`, иначе он не откладывает решение, а
        // отменяет его (см. докблок типа).
        let sessions = self.gate(sessions, mic_busy);
        let (active, event) = poll_to_event(self.was_active, sessions, me);
        self.was_active = active.is_some();
        (active, event)
    }

    /// На Windows гейта нет: WASAPI-сессия в состоянии Active — это уже полный
    /// сигнал «микрофон держат», второго источника ему не нужно.
    #[cfg(not(target_os = "macos"))]
    fn gate(&mut self, sessions: Vec<MicSession>, _mic_busy: bool) -> Vec<MicSession> {
        sessions
    }

    /// На macOS «известный процесс» сам по себе ничего не значит: Zoom/Teams/
    /// Slack/Discord держатся открытыми и без звонка. Сессия доезжает до
    /// `poll_to_event` только вместе с чужим захватом микрофона, и на
    /// восходящем фронте захват обязан продержаться несколько опросов подряд
    /// (см. [`MAC_BUSY_POLLS_BEFORE_ARM`]). Обратно сессия НЕ пропадает от
    /// первого же свободного опроса (см. [`MAC_FREE_POLLS_BEFORE_DROP`]).
    ///
    /// Пустой список сюда доходит и проходит насквозь: любая ветка ниже вернёт
    /// его же (пустой), то есть `SessionGone` на закрытие звонилки приходит
    /// сразу и терпению не подлежит. `was_active` поднимается в `true`
    /// ИСКЛЮЧИТЕЛЬНО через ветку «микрофон занят», которая счётчик свободных
    /// опросов обнуляет, поэтому просроченное значение не доживает до
    /// следующего взвода.
    #[cfg(target_os = "macos")]
    fn gate(&mut self, sessions: Vec<MicSession>, mic_busy: bool) -> Vec<MicSession> {
        if mic_busy {
            self.free_polls = 0;
            // Звонок уже идёт — захват просто подтверждает это.
            if self.was_active {
                return sessions;
            }
            // Захват без единого известного процесса разгон не копит: иначе
            // диктовка, закончившаяся до запуска Zoom, подарила бы ему готовый
            // разгон и мгновенный взвод.
            if sessions.is_empty() {
                self.busy_polls = 0;
                return sessions;
            }
            self.busy_polls += 1;
            if self.busy_polls >= MAC_BUSY_POLLS_BEFORE_ARM {
                return sessions;
            }
            return Vec::new();
        }
        // Микрофон свободен. Разгон обрывается: короткие захваты не копятся
        // между собой.
        self.busy_polls = 0;
        // На восходящем фронте это отказ: «Zoom открыт» не повод предлагать
        // запись. Решение не теряется, а откладывается — `was_active`
        // останется `false`, и первый же достаточно долгий захват даст честный
        // `SessionAppeared`, хоть через полчаса.
        if !self.was_active {
            return Vec::new();
        }
        // Звонок уже идёт, а микрофон отпустили (mute или конец звонка):
        // терпим до минуты, потом считаем его законченным.
        self.free_polls += 1;
        if self.free_polls >= MAC_FREE_POLLS_BEFORE_DROP {
            Vec::new()
        } else {
            sessions
        }
    }
}

/// Второй сигнал детекта: держит ли микрофон кто-то, кроме нас.
#[cfg(target_os = "macos")]
fn mic_busy(det: &MacDetector, me: u32) -> Result<bool, DetectError> {
    det.mic_in_use_by_others(me)
}

/// На Windows второго сигнала нет — гейт его не читает (см. `Detect::gate`).
#[cfg(not(target_os = "macos"))]
fn mic_busy(_det: &WindowsDetector, _me: u32) -> Result<bool, DetectError> {
    Ok(true)
}

/// Проверить, что тап создаётся, — или сообщить, почему не вышло.
///
/// Только проба (`SystemTap::probe`): тап создаётся и тут же сносится, без
/// агрегата и без открытия устройств, так что индикатор микрофона от неё не
/// загорается. Настоящий тап поднимает `MacAudio::open` на взводе, ручном
/// старте или проверке микрофона и гасит `MacAudio::close`.
///
/// `MR_FORCE_NO_SYSTEM_AUDIO=1` заставляет пробу «провалиться», не трогая при
/// этом ни одного разрешения в системе. Тот же приём, что `MR_DEBUG_TIMING` и
/// `MR_DEBUG_POLL`: живого отказа не поймать иначе как отказавшись руками, а
/// путь, который включается один раз на первом запуске, обязан быть проверяем
/// не один раз.
///
/// Заведено не для красоты. `tccutil reset` оказался ненадёжным способом
/// вернуться к «разрешение ещё не спрашивали»: сброс и `ScreenCapture`, и
/// `AudioCapture` для нашего bundle id отрабатывает с «Successfully reset», а
/// тап после этого поднимается как ни в чём не бывало. Без этой переменной
/// весь режим одного микрофона — ветка, которую нельзя запустить ни в тесте,
/// ни руками.
#[cfg(target_os = "macos")]
fn probe_system_tap() -> Result<(), String> {
    if std::env::var_os("MR_FORCE_NO_SYSTEM_AUDIO").is_some() {
        return Err("захват выключен вручную (MR_FORCE_NO_SYSTEM_AUDIO)".to_string());
    }
    meeting_recorder::capture::SystemTap::probe().map_err(|e| e.to_string())
}

/// Крутится в СВОЁМ потоке. Detector и App конструируются здесь и отсюда не
/// уезжают — оба `!Send`.
pub fn run(
    handle: AppHandle,
    rx: Receiver<Ctl>,
    root: PathBuf,
    mic: DeviceChoice,
    monitor_epoch: MonitorEpoch,
) {
    let status = handle.state::<Status>();
    // Видео идёт следом за записью звука своим потоком — см. `screen.rs`.
    let mut screen = crate::screen::Follower::spawn(handle.clone(), root.clone());
    // Решение живёт в ядре (`capture::macos`), а не здесь: требование к версии —
    // свойство Process Tap API, и отказывать по нему обязаны оба бинаря
    // одинаково и одними словами. Консоль зовёт ту же функцию.
    #[cfg(target_os = "macos")]
    if let Some(why) = meeting_recorder::capture::macos::unsupported_reason() {
        status::fatal(&handle, why);
        return;
    }
    #[cfg(target_os = "windows")]
    let det = WindowsDetector::new();
    #[cfg(target_os = "macos")]
    let det: Result<MacDetector, meeting_recorder::detector::DetectError> = Ok(MacDetector::new());
    let det = match det {
        Ok(d) => d,
        Err(e) => {
            // Через status::fatal, а не голым emit: это происходит в setup(), то
            // есть раньше, чем webview успевает подписаться, — событие ушло бы в
            // пустоту, и в релизе от ошибки не осталось бы следа вообще.
            status::fatal(&handle, format!("детектор не поднялся: {e}"));
            return;
        }
    };
    #[cfg(target_os = "windows")]
    let mut app = App::new(root, mic);
    // Системный тап на macOS здесь НЕ поднимается: он живёт только пока
    // открыт захват (`MacAudio::open`/`close` — взвод, запись, проверка
    // микрофона). Тап, живший весь процесс, держал вход гарнитуры, и оранжевый
    // индикатор горел весь день при пустом приложении (см. докблок
    // `MacAudio`). Здесь только проба разрешения — без открытия устройств.
    //
    // Отказ пробы НЕ фатален. `.expect(...)` когда-то означал тихую панику в
    // единственном потоке, который умеет писать на диск, а `status::fatal`
    // после него был честен, но строг не по делу: микрофон-то захватывается.
    // Дизайн-документ обещает деградацию с видимым предупреждением — так и
    // сделано: пишется один микрофон.
    //
    // Автодетект в этом режиме работает: он смотрит на чужой захват
    // микрофона (`MacDetector::mic_in_use_by_others`), а не на системный звук.
    #[cfg(target_os = "macos")]
    let mut app = {
        let audio: Box<dyn meeting_recorder::app::AudioIo> = match probe_system_tap() {
            Ok(()) => Box::new(meeting_recorder::app::MacAudio::new(mic)),
            Err(why) => {
                status::no_system_audio(&handle, why);
                Box::new(meeting_recorder::app::MacAudio::new_mic_only(mic))
            }
        };
        App::new_with_audio(root, audio)
    };
    let me = std::process::id();
    // Память детекта между опросами живёт здесь целиком — см. докблок `Detect`.
    let mut detect = Detect::default();
    // Слежка за записью «Зайти и записать» — см. докблок `MeetingWatch`.
    let mut watch = MeetingWatch::default();
    let mut active: Option<MicSession> = None;
    // None — «ещё не опрашивали», первый опрос идёт сразу. Считать
    // `Instant::now() - POLL_INTERVAL` нельзя: вычитание у Instant паникует,
    // если результат не представим.
    let mut last_poll: Option<Instant> = None;
    // Проверка, забытая включённой, держала бы микрофон бесконечно. Таймер
    // считает здесь, а не в webview: окно можно закрыть, и выключать проверку
    // стало бы некому.
    let mut monitor_since: Option<Instant> = None;

    loop {
        // Снимок ДО обработки этого тика — единственный способ увидеть
        // переход «было включено → стало выключено» уже после того, как он
        // случился. См. докблок `should_emit_levels`.
        let was_monitoring = app.is_monitoring();

        if last_poll.is_none_or(|t| t.elapsed() >= POLL_INTERVAL) {
            last_poll = Some(Instant::now());
            // Второй сигнал спрашивается только при открытой звонилке: без
            // неё гейт всё равно вернёт пустой список, и ответ ничего бы не
            // изменил. В простое без Zoom/Teams/Slack/Discord к Core Audio
            // этот цикл не обращается вовсе.
            let polled = det.poll().and_then(|sessions| {
                let busy = if sessions.is_empty() {
                    false
                } else {
                    mic_busy(&det, me)?
                };
                Ok((sessions, busy))
            });
            match polled {
                Ok((sessions, busy)) => {
                    // `Detect::step` фильтрует НАШ pid (через `poll_to_event`):
                    // без этого приложение детектит само себя (мы держим мик в
                    // Armed и в записи), SessionGone не приходит никогда,
                    // запись не останавливается по концу звонка. Он же на
                    // macOS применяет гейт по чужому микрофону — до
                    // `poll_to_event`, а не после, иначе гейт не откладывает
                    // детект, а отменяет его (см. докблок `Detect`).
                    let (found, event) = detect.step(sessions, busy, me);
                    active = found;

                    if let Some(e) = event {
                        feed(&mut app, &handle, e, active.as_ref());
                        if let (true, Some(s)) = (app.state_is_armed(), active.as_ref()) {
                            // В интерфейс уходит канонический идентификатор, а
                            // не сырое имя процесса: на Windows оно другое
                            // (`Zoom.exe` против `zoom.us`), и таблицы во
                            // всплывашке на него не отзывались.
                            let source = meeting_recorder::detector::canonical_source(&s.process_name);
                            match crate::calendar::on_detector_armed(&handle) {
                                crate::calendar::DetectorAnswer::Classic => ask(&handle, source),
                                crate::calendar::DetectorAnswer::Calendar(p) => {
                                    ask_calendar(&handle, source, &p)
                                }
                                // По этой встрече уже смахнули плашку: смахнуть =
                                // не записывать (канон 2.8). Отказ уходит в машину
                                // сразу — кольцо выбрасывается, микрофон отпущен.
                                crate::calendar::DetectorAnswer::Silent => {
                                    log::info!("календарь: по встрече уже отказались — не спрашиваю");
                                    feed(&mut app, &handle, Event::UserDeclined, active.as_ref());
                                }
                            }
                        }
                    }
                    // «Зайти и записать»: конец звонка останавливает запись,
                    // но только если звонок после старта хоть раз был виден.
                    let manual = app.state() == State::Recording(Trigger::Manual);
                    if watch.step(manual, active.is_some(), event) {
                        log::info!("календарь: звонок кончился — останавливаю запись встречи");
                        feed(&mut app, &handle, Event::ManualStop, None);
                    }
                }
                // Ошибку опроса нельзя трактовать как «сессия исчезла»: сбой
                // COM/WASAPI/Core Audio на один тик оборвал бы идущую
                // авто-запись и тут же переспросил «записать?» посреди встречи.
                // Молча держим прошлое состояние — ручной стоп у пользователя
                // никто не отнимал.
                Err(e) => eprintln!("детектор: {e} (состояние сохранено)"),
            }
        }

        let quit = drain_ctl(
            &mut app,
            &rx,
            active.as_ref(),
            &monitor_epoch,
            &mut watch,
            |a, e, src| feed(a, &handle, e, src),
            |msg| {
                let _ = handle.emit("error", msg.clone());
                eprintln!("{msg}");
            },
        );
        if quit {
            // Финализация уже прошла внутри drain_ctl — см. её докблок.
            // Видео дописывается отдельно и до выхода: иначе от mp4 остался
            // бы файл без индекса, который не открывается.
            screen.shutdown();
            handle.exit(0);
            return;
        }

        // Взводим/снимаем таймер по факту состояния, а не по команде: так копия
        // «включена ли проверка» не может разъехаться с истиной в App.
        match (app.is_monitoring(), monitor_since) {
            (true, None) => monitor_since = Some(Instant::now()),
            (false, Some(_)) => monitor_since = None,
            (true, Some(t)) if t.elapsed() >= MONITOR_TIMEOUT => {
                if let Err(e) = app.set_monitor(false) {
                    eprintln!("автовыключение проверки: {e}");
                }
                monitor_since = None;
            }
            _ => {}
        }

        if let Err(e) = app.pump_audio() {
            let _ = handle.emit("error", e.to_string());
            eprintln!("прокачка аудио: {e}");
        }
        if app.take_unmute_question() {
            ask_unmute(&handle);
        }
        sync(&handle, &app, &status);
        if app.take_mic_switched() {
            emit_mic_switched(&handle);
        }
        screen.follow(app.current_recording());

        // Рассылка уровней — только когда есть что показывать (в простое это
        // было бы 5 событий в секунду в пустоту), но обязательно включая тик,
        // на котором проверка ТОЛЬКО ЧТО выключилась — иначе окно застревает
        // в «идёт проверка» навсегда. См. докблок `should_emit_levels`.
        if should_emit_levels(was_monitoring, app.is_monitoring(), app.state()) {
            let l = levels_to_emit(app.levels(), app.is_monitoring(), app.state());
            let _ = handle.emit(
                "levels",
                serde_json::json!({
                    // Выключенный микрофон — пустая полоска: в файл идёт
                    // тишина, и полоска обязана показывать то, что пишется.
                    // Сам уровень в ядре остаётся настоящим — см. `pump_audio`.
                    "mic": if app.is_mic_muted() { 0.0 } else { l.mic },
                    "system": l.system,
                    "monitoring": app.is_monitoring(),
                    "epoch": monitor_epoch.load(Ordering::SeqCst),
                }),
            );
        }

        std::thread::sleep(TICK);
    }
}

