    /// Комментарий у ASK_WIDTH годами утверждал, что ширина дублируется в
    /// tauri.conf.json. Она там другая: 876 — это ширина ОКНА, с полем справа
    /// под уезжающую плашку, а ASK_WIDTH — ширина самой плашки. Тест держит
    /// оба числа сверенными с конфигом, чтобы комментарий больше не врал.
    #[test]
    fn ширина_плашки_и_окна_это_разные_числа() {
        let conf: serde_json::Value =
            serde_json::from_str(include_str!("../tauri.conf.json")).expect("конфиг");
        let окно = conf["app"]["windows"]
            .as_array()
            .expect("список окон")
            .iter()
            .find(|w| w["label"] == "ask")
            .expect("окно ask");

        assert_eq!(окно["height"].as_f64(), Some(ASK_HEIGHT));
        assert_eq!(окно["width"].as_f64(), Some(ASK_WINDOW_WIDTH));
        // Правый край окна должен быть не левее правого края экрана, иначе
        // плашка 440 обрезалась бы границей окна, не долетев до края экрана.
        // Сейчас окно выходит за экран на 876 − 16 − 440 − 12 = 408.
        assert!(
            ASK_WINDOW_WIDTH >= ASK_LEFT_GUTTER + CAL_ASK_WIDTH + ASK_RIGHT_MARGIN,
            "справа от плашки 440 должен остаться путь, по которому она уедет за край экрана"
        );
    }

