//! «Похоже, вы говорите при выключенном микрофоне» — когда спросить человека.
//!
//! Микрофон выключают из-за шума вокруг, поэтому громкость сама по себе ничего
//! не значит: шумно было и до вопроса. Признак речи здесь — отрыв от шумовой
//! полки ЭТОГО выключения: голос у микрофона громче фона, на котором его
//! выключили. Полка падает мгновенно и растёт медленно — так продолжительная
//! речь не успевает стать «фоном», а стихший шум сразу опускает планку.
//!
//! Решение — по доле громких кадров за последние две секунды, а не по одному
//! пику: хлопок двери или кашель не должны спрашивать «вы говорите?».
//!
//! Ложное срабатывание (собака, телевизор) стоит одного смахивания плашки,
//! поэтому после вопроса детектор молчит минуту, а после явного «нет» — пять.
//!
//! Время считается сэмплами, а не тиками и не часами: кусок, вынутый из
//! захвата за тик, бывает разной длины, а сэмплы — это и есть время звука.

use crate::storage::SAMPLE_RATE;
use std::collections::VecDeque;

/// Кадр — 100 мс. Короче — слоги рвут речь на «громко/тихо», длиннее — пауза
/// между фразами смазывается с речью.
const FRAME: usize = SAMPLE_RATE as usize / 10;

/// Окно решения — 2 с, то есть 20 кадров.
const WINDOW_FRAMES: usize = 20;

/// Сколько кадров окна должны быть громкими — 1.2 с из 2. У живой речи паузы
/// между словами есть, но короче.
const LOUD_FRAMES: usize = 12;

/// На сколько дБ кадр должен быть громче полки, чтобы считаться речью.
const MARGIN_DB: f32 = 10.0;

/// Ниже этого уровня кадр не речь, как бы ни была тиха полка. Та же граница,
/// что у пометки «вас почти не слышно» (`imbalance::MIN_SPEECH_DBFS`): тише —
/// голос уже тонет в шуме любого тракта.
const MIN_SPEECH_DBFS: f32 = -50.0;

/// Насколько полка подтягивается вверх за кадр: 0.5% разницы. При речи на
/// 25 дБ выше фона это ~0.12 дБ за кадр — за две секунды разговора полка
/// поднимается на пару дБ, а не догоняет голос.
const FLOOR_RISE: f32 = 0.005;

/// Первые 2 с после выключения не судятся: человек мог нажать кнопку, не
/// договорив слово.
const GRACE: u64 = 2 * SAMPLE_RATE as u64;

/// Молчать после вопроса, на который не ответили, — минута.
pub const COOLDOWN: u64 = 60 * SAMPLE_RATE as u64;

/// Молчать после явного «нет» (плашку смахнули) — пять минут: человек
/// говорит с кем-то в комнате и об этом уже сказал.
pub const SNOOZE: u64 = 5 * 60 * SAMPLE_RATE as u64;

#[derive(Default)]
pub struct MutedSpeech {
    /// Хвост сэмплов, не добравший до целого кадра.
    pending: Vec<i16>,
    floor_db: Option<f32>,
    /// Громкий ли кадр — по последним `WINDOW_FRAMES` кадрам.
    recent: VecDeque<bool>,
    /// Сколько сэмплов прошло с выключения.
    elapsed: u64,
    /// Сколько сэмплов ещё молчать.
    quiet_for: u64,
}

impl MutedSpeech {
    /// Начать заново — на каждом выключении: полка прошлого выключения к
    /// новому шуму отношения не имеет.
    pub fn reset(&mut self) {
        *self = Self::default();
    }

    /// Не спрашивать ближайшие `samples` сэмплов.
    pub fn snooze(&mut self, samples: u64) {
        self.quiet_for = self.quiet_for.max(samples);
        self.recent.clear();
    }

    /// Скормить звук выключенного микрофона. `true` — пора спросить; после
    /// этого детектор сам замолкает на [`COOLDOWN`].
    pub fn feed(&mut self, samples: &[i16]) -> bool {
        self.pending.extend_from_slice(samples);
        let mut ask = false;
        let frames = self.pending.len() / FRAME;
        for i in 0..frames {
            let db = frame_dbfs(&self.pending[i * FRAME..(i + 1) * FRAME]);
            ask |= self.frame(db);
        }
        self.pending.drain(..frames * FRAME);
        ask
    }

    fn frame(&mut self, db: f32) -> bool {
        self.elapsed += FRAME as u64;
        self.quiet_for = self.quiet_for.saturating_sub(FRAME as u64);

        let floor = match self.floor_db {
            Some(f) if db >= f => f + (db - f) * FLOOR_RISE,
            _ => db,
        };
        self.floor_db = Some(floor);

        let loud = db >= MIN_SPEECH_DBFS && db >= floor + MARGIN_DB;
        self.recent.push_back(loud);
        if self.recent.len() > WINDOW_FRAMES {
            self.recent.pop_front();
        }

        if self.elapsed <= GRACE || self.quiet_for > 0 {
            return false;
        }
        if self.recent.iter().filter(|l| **l).count() < LOUD_FRAMES {
            return false;
        }
        self.snooze(COOLDOWN);
        true
    }
}

/// RMS кадра в dBFS; цифровой ноль — −120, как пол в `imbalance`.
fn frame_dbfs(frame: &[i16]) -> f32 {
    let sum: f64 = frame.iter().map(|s| (*s as f64).powi(2)).sum();
    let rms = (sum / frame.len().max(1) as f64).sqrt() / i16::MAX as f64;
    if rms <= 0.0 {
        return -120.0;
    }
    (20.0 * rms.log10()).max(-120.0) as f32
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `секунд` звука с амплитудой `амплитуда` (доля полной шкалы) —
    /// прямоугольник ±A, его RMS равен A.
    fn звук(секунд: f32, амплитуда: f32) -> Vec<i16> {
        let n = (секунд * SAMPLE_RATE as f32) as usize;
        let a = (амплитуда * i16::MAX as f32) as i16;
        (0..n).map(|i| if i % 2 == 0 { a } else { -a }).collect()
    }

    /// Кормить кусками по 200 мс, как настоящий тик, и сказать, спросил ли.
    fn скормить(д: &mut MutedSpeech, звук: &[i16]) -> bool {
        звук.chunks(3200).fold(false, |спросил, кусок| д.feed(кусок) | спросил)
    }

    #[test]
    fn речь_над_шумом_спрашивает() {
        let mut д = MutedSpeech::default();
        // Шум −40 дБ (0.01), на нём и выключили.
        assert!(!скормить(&mut д, &звук(3.0, 0.01)), "фон — не повод спрашивать");
        // Голос −20 дБ (0.1), на 20 дБ над фоном.
        assert!(скормить(&mut д, &звук(1.5, 0.1)));
    }

    #[test]
    fn ровный_громкий_шум_не_спрашивает() {
        let mut д = MutedSpeech::default();
        assert!(!скормить(&mut д, &звук(10.0, 0.2)), "громко, но всё время одинаково — это фон");
    }

    #[test]
    fn короткий_хлопок_не_речь() {
        let mut д = MutedSpeech::default();
        скормить(&mut д, &звук(3.0, 0.01));
        assert!(!скормить(&mut д, &звук(0.4, 0.5)));
        assert!(!скормить(&mut д, &звук(2.0, 0.01)));
    }

    #[test]
    fn сразу_после_выключения_не_спрашивает() {
        let mut д = MutedSpeech::default();
        // Человек договаривает фразу, нажимая кнопку.
        assert!(!скормить(&mut д, &звук(1.8, 0.1)));
    }

    #[test]
    fn тихий_голос_ниже_порога_речи_не_спрашивает() {
        let mut д = MutedSpeech::default();
        скормить(&mut д, &звук(3.0, 0.0001));
        // −66 дБ: над полкой, но тише любого живого голоса у микрофона.
        assert!(!скормить(&mut д, &звук(2.0, 0.0005)));
    }

    #[test]
    fn после_вопроса_минуту_молчит() {
        let mut д = MutedSpeech::default();
        скормить(&mut д, &звук(3.0, 0.01));
        assert!(скормить(&mut д, &звук(1.5, 0.1)));
        assert!(!скормить(&mut д, &звук(30.0, 0.1)), "не переспрашивает каждые две секунды");
    }

    #[test]
    fn после_явного_нет_пять_минут_молчит() {
        let mut д = MutedSpeech::default();
        скормить(&mut д, &звук(3.0, 0.01));
        assert!(скормить(&mut д, &звук(1.5, 0.1)));
        д.snooze(SNOOZE);
        let мало = SNOOZE as f32 / SAMPLE_RATE as f32 - 5.0;
        // Тишина между разговорами, чтобы полка вернулась к фону.
        assert!(!скормить(&mut д, &звук(мало, 0.01)));
        assert!(!скормить(&mut д, &звук(2.0, 0.1)), "пять минут ещё не прошли");
        скормить(&mut д, &звук(10.0, 0.01));
        assert!(скормить(&mut д, &звук(2.0, 0.1)), "прошли — снова спрашивает");
    }

    #[test]
    fn сброс_начинает_заново() {
        let mut д = MutedSpeech::default();
        скормить(&mut д, &звук(3.0, 0.01));
        assert!(скормить(&mut д, &звук(1.5, 0.1)));
        д.reset();
        скормить(&mut д, &звук(3.0, 0.01));
        assert!(скормить(&mut д, &звук(1.5, 0.1)), "новое выключение — новая история");
    }
}
