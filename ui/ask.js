const тише = matchMedia("(prefers-reduced-motion: reduce)").matches;

// Текущее положение плашки: x — сдвиг вправо от места покоя, y — вверх/вниз.
let x = 0;
let y = 0;
let живо = false;
let кадр = null;

/// Единственное место, которое трогает трансформацию.
function нарисовать() {
  $("card").style.transform = `translate3d(${x.toFixed(2)}px, ${y.toFixed(2)}px, 0)`;
}

function стоп() {
  if (кадр) cancelAnimationFrame(кадр);
  кадр = null;
}

/// Пружина без передержки. Считается от ТЕКУЩЕГО положения, а не от целевого,
/// поэтому её можно перехватить на полпути и развернуть без скачка. Затухание
/// критическое (c = 2√k): отскок уместен там, где перед ним был бросок, а не
/// там, где плашка просто встаёт на место.
function пружина({ от, к, скорость = 0, жёсткость = 170, шаг, конец }) {
  стоп();
  if (тише) {
    шаг(к);
    конец?.();
    return;
  }
  let п = от;
  let v = скорость;
  const c = 2 * Math.sqrt(жёсткость);
  let t0 = performance.now();
  const тик = (t) => {
    const dt = Math.min((t - t0) / 1000, 1 / 30);
    t0 = t;
    v += (-жёсткость * (п - к) - c * v) * dt;
    п += v * dt;
    if (Math.abs(п - к) < 0.3 && Math.abs(v) < 8) {
      шаг(к);
      кадр = null;
      конец?.();
      return;
    }
    шаг(п);
    кадр = requestAnimationFrame(тик);
  };
  кадр = requestAnimationFrame(тик);
}

/// Куда жест доедет по инерции. Формула Apple из «Designing Fluid Interfaces»:
/// экспоненциальное затухание, а не школьное v²/2a. Нужна, чтобы короткий
/// быстрый флик смахивал, а долгое медленное таскание — нет.
function доедет(скорость, торможение = 0.998) {
  return ((скорость / 1000) * торможение) / (1 - торможение);
}

/// Сопротивление за границей: чем дальше тянут влево, тем меньше плашка идёт
/// следом. Жёсткий упор читался бы как «зависло».
function резинка(перебор, размер, к = 0.55) {
  return (перебор * размер * к) / (размер + к * Math.abs(перебор));
}

/// Показать вопрос: плашка выезжает сверху, из-под края экрана.
function показать() {
  const card = $("card");
  card.classList.remove("in");
  void card.offsetWidth;
  card.classList.add("in");
  живо = true;
  const высота = $("wrap").getBoundingClientRect().height;
  x = 0;
  y = -(высота + 24);
  нарисовать();
  пружина({
    от: y,
    к: 0,
    жёсткость: 200,
    шаг: (v) => {
      y = v;
      нарисовать();
    },
  });
}

/// Убрать. Уходит всегда ВБОК, вправо: и когда смахнули, и когда вышло время,
/// и когда ответили. Так делают системные уведомления macOS — приходят сверху,
/// уходят за правый край, — и так один и тот же исход выглядит одинаково,
/// чем бы он ни был вызван.
///
/// `скорость` приходит со смахивания: брошенное рукой обязано долететь с той
/// скоростью, с какой его бросили, иначе между жестом и анимацией виден шов.
function убрать(скорость = 0) {
  if (!живо) return;
  живо = false;
  // Улетает в запас справа и обрезается краем экрана. Жёсткость ниже
  // обычной: уходящее должно долетать, а не тормозить у цели.
  пружина({
    от: x,
    к: ШИРИНА_ОКНА,
    скорость,
    жёсткость: 110,
    шаг: (v) => {
      x = v;
      нарисовать();
    },
    конец: () => окно.hide().catch(() => {}),
  });
}

/// Отправить ответ в машину записи. Не ждём подтверждения перед тем, как
/// убрать плашку: пауза между действием и откликом — это ровно то, из-за чего
/// интерфейс перестаёт ощущаться прямым. Ошибку глотать нельзя, но показать её
/// здесь негде — плашка уже уезжает; её видимая половина (состояние не
/// изменилось) остаётся в главном окне и в трее.
function ответить(имя, скорость = 0) {
  invoke("send_event", { name: имя }).catch((e) => console.error("ответ не ушёл:", e));
  убрать(скорость);
}

$("yes").addEventListener("click", () => ответить("confirm"));

// Время вышло — вопрос уезжает молча. Это НЕ ответ, в отличие от смахивания:
// запись не начинается, но и отказа не было — состояние «взвод» остаётся, и
// вопрос по-прежнему доступен в главном окне и в трее. Разница намеренная:
// не заметить вопрос и отказаться от него — разные вещи.
$("life").addEventListener("animationend", () => убрать());

// Наведение. Считает его Rust по положению курсора и присылает готовым
// событием: окно неактивного приложения движений мыши от macOS не получает,
// поэтому ни `:hover`, ни `mouseenter` здесь не срабатывают. Пока мышь на
// плашке, отсчёт стоит — иначе вопрос уезжает из-под читающего.
listen("hover", (e) => {
  document.body.classList.toggle("наведено", e.payload === true);
});

// ── Смахивание вправо ────────────────────────────────────────────────────
// Слежение 1:1 всё время жеста, а не только по его концу: готовое событие
// «свайп случился» выбрасывает ровно ту непрерывность, ради которой жест и
// нужен. Решение принимается по СКОРОСТИ, а не по одному лишь пути, — короткий
// быстрый флик должен смахивать.
(function () {
  let скорость = 0;
  let отпустили = null;

  const решить = () => {
    if (!живо) return;
    if (x + доедет(скорость) > ПОРОГ) {
      // Смахнули — значит «не записывать». Это полноценный ответ, а не просто
      // «убрать с глаз»: машина уходит из «взвода», и вопрос больше не висит
      // ни в главном окне, ни в трее.
      ответить("decline", скорость);
    } else {
      пружина({
        от: x,
        к: 0,
        скорость,
        шаг: (v) => {
          x = v;
          нарисовать();
        },
      });
    }
    скорость = 0;
  };

  const тянуть = (куда, мгновенная) => {
    // Влево от места покоя плашке ехать некуда — там край экрана.
    x = куда >= 0 ? куда : -резинка(-куда, ПЛАШКА);
    скорость = мгновенная;
    нарисовать();
  };

  addEventListener(
    "wheel",
    (e) => {
      if (!живо || Math.abs(e.deltaX) < Math.abs(e.deltaY)) return;
      e.preventDefault();
      стоп();
      const было = x;
      тянуть(x - e.deltaX, 0);
      скорость = (x - было) * 60;
      // Трекпад не сообщает об отпускании пальцев — считаем жест законченным,
      // когда события кончились.
      clearTimeout(отпустили);
      отпустили = setTimeout(решить, 90);
    },
    { passive: false },
  );

  // То же мышью. Захват указателя — чтобы слежение не обрывалось, когда
  // курсор ушёл за плашку.
  let схватили = null;
  let было = 0;
  let когда = 0;
  addEventListener("pointerdown", (e) => {
    if (!живо || e.target.closest("button")) return;
    стоп();
    схватили = e.clientX - x;
    было = x;
    когда = performance.now();
    document.body.setPointerCapture(e.pointerId);
  });
  addEventListener("pointermove", (e) => {
    if (схватили === null) return;
    const dt = Math.max(performance.now() - когда, 1) / 1000;
    const куда = e.clientX - схватили;
    тянуть(куда, (x - было) / dt);
    было = x;
    когда = performance.now();
  });
  addEventListener("pointerup", () => {
    if (схватили === null) return;
    схватили = null;
    решить();
  });
})();

