/// Убрать. Уходит всегда ВБОК, вправо: и когда смахнули, и когда вышло время,
/// и когда ответили. Так делают системные уведомления macOS — приходят сверху,
/// уходят за правый край, — и так один и тот же исход выглядит одинаково,
/// чем бы он ни был вызван.
///
/// `скорость` приходит со смахивания: брошенное рукой обязано долететь с той
/// скоростью, с какой его бросили, иначе между жестом и анимацией виден шов.
function убрать(скорость = 0) {
  if (!живо) return;
  живо = false;
  закрыть_меню();
  clearInterval(таймер_подписи);
  // Улетает в запас справа и обрезается краем экрана. Жёсткость ниже
  // обычной: уходящее должно долетать, а не тормозить у цели.
  пружина({
    от: x,
    к: ШИРИНА_ОКНА,
    скорость,
    жёсткость: 110,
    шаг: (v) => {
      x = v;
      нарисовать();
    },
    конец: () => окно.hide().catch(() => {}),
  });
}

/// «Через 1 мин», «Начинается», «Началась 2 мин назад»; в режиме «Записать»
/// — «Идёт сейчас» (мокап, «Звонилка уже заняла микрофон»).
function подпись_времени(в, сейчас) {
  if (в.mode === "record") return i18n.t("calendar.now");
  const до = в.start_ms - сейчас;
  if (до > 30_000) return i18n.t("calendar.inMin", { n: Math.max(1, Math.round(до / 60_000)) });
  if (до > -60_000) return i18n.t("calendar.starting");
  return i18n.t("calendar.startedAgo", { n: Math.floor(-до / 60_000) });
}

function обновить_подпись() {
  if (!встреча) return;
  $("src").textContent = `${подпись_времени(встреча, Date.now())} · ${ИМЕНА_ВСТРЕЧ[встреча.source] ?? ""}`;
}

/// Вернуть плашку к вопросу «Записать встречу?». Нужна, потому что окно одно
