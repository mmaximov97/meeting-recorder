function режим_встречи(в) {
  вопрос = "record";
  встреча = в;
  закрыть_меню();
  document.body.classList.add("кал");
  document.body.classList.toggle("кал-вход", в.mode === "join");
  плашка = ПЛАШКА_КАЛЕНДАРЬ;
  $("title").textContent = в.title || i18n.t("calendar.untitled");
  $("yes").textContent = в.mode === "join" ? i18n.t("calendar.join") : i18n.t("record.confirm");
  $("yes").disabled = false;
  // В режиме «Записать» ⋯ нет: «подключиться без записи» уже случилось.
  $("more").hidden = в.mode !== "join";
  $("more").disabled = false;
  const ava = $("ava");
  ava.className = в.source === "zoom" ? "ava zoom" : в.source === "teams" ? "ava teams" : "ava";
  ava.innerHTML = в.source === "zoom" ? ZOOM_SVG : в.source === "teams" ? "T" : КАМЕРА_SVG;
  // Линия жизни «Зайти и записать» идёт по часам встречи: появилась позже
  // (запуск приложения в 15:01) — начинается не с полной длины.
  const life = $("life");
  if (в.mode === "join") {
    const осталось = Math.max(в.tail_ms - Date.now(), 0);
    life.style.animationDuration = `${ЖИЗНЬ_ВСТРЕЧИ_МС}ms`;
    life.style.animationDelay = `${-(ЖИЗНЬ_ВСТРЕЧИ_МС - осталось)}ms`;
  } else {
    life.style.animationDuration = "";
    life.style.animationDelay = "";
  }
  обновить_подпись();
  clearInterval(таймер_подписи);
  таймер_подписи = setInterval(обновить_подпись, 15_000);
}

/// «Зайти и записать» / «Подключиться без записи». Кнопки гаснут сразу,
/// второй клик ничего не делает (канон 3.6); ссылку открывает и запись
/// запускает Rust.
function зайти(с_записью) {
  if (!встреча || $("yes").disabled) return;
  $("yes").disabled = true;
  $("more").disabled = true;
  закрыть_меню();
  invoke("calendar_join", { id: встреча.id, record: с_записью }).catch((e) =>
    console.error("встреча не открылась:", e),
  );
  убрать();
}

// ── Меню ⋯ (путь B) ─────────────────────────────────────────────────────
// Сначала окно вырастает, потом показывается меню — иначе нижний край меню
// на кадр обрезался бы границей окна. Закрывается: пункт, повторный ⋯,
// клик по плашке, смахивание, уход плашки и через 8 секунд само — клики в
// чужих окнах до нас не доходят, а прозрачная полоса под плашкой, пока
// окно высокое, перехватывает клики.
async function открыть_меню() {
  if (!встреча || встреча.mode !== "join") return;
  try {
    await invoke("ask_menu", { open: true });
  } catch (e) {
    console.error("меню не открылось:", e);
    return;
  }
  // Пока ждали ответ, плашку могли убрать: меню открывать не во что. Размер
  // окну задаст следующий показ (show_ask_popup ставит его каждый раз).
  if (!живо) return;
  $("pmenu").hidden = false;
  $("more").classList.add("open");
  clearTimeout(таймер_меню);
  таймер_меню = setTimeout(закрыть_меню, 8000);
}

function закрыть_меню() {
  clearTimeout(таймер_меню);
  if ($("pmenu").hidden) return;
  $("pmenu").hidden = true;
  $("more").classList.remove("open");
  invoke("ask_menu", { open: false }).catch(() => {});
}

/// Отправить ответ в машину записи. Не ждём подтверждения перед тем, как
/// убрать плашку: пауза между действием и откликом — это ровно то, из-за чего
/// интерфейс перестаёт ощущаться прямым. Ошибку глотать нельзя, но показать её
/// здесь негде — плашка уже уезжает; её видимая половина (состояние не
/// изменилось) остаётся в главном окне и в трее.
function ответить(имя, скорость = 0) {
  invoke("send_event", { name: имя }).catch((e) => console.error("ответ не ушёл:", e));
  убрать(скорость);
}

// О чём сейчас спрашивает плашка. Окно одно на три вопроса: «записать
// встречу?» (во взводе), встреча из календаря и «вы говорите? микрофон
// выключен» (в записи). Одновременно их не бывает — первые два живут только до
// начала записи, третий только в ней, — поэтому второе окно заводить незачем:
// позиционирование, NSPanel и наведение у них общие (см. `show_ask_popup` в
// audio.rs). Календарь узнаётся по `встреча`, здесь — только «unmute» или нет.
let вопрос = "record";

/// Ответ на вопрос «вы говорите?». «Да» включает микрофон; «нет» (смахнули)
/// просит не спрашивать подольше. Тот же принцип, что у `ответить`: плашка
/// уезжает сразу, не дожидаясь бэкенда.
function ответить_про_микрофон(включить, скорость = 0) {
  const действие = включить
    ? invoke("set_mic_muted", { muted: false })
    : invoke("decline_unmute_question");
  действие.catch((e) => console.error("ответ не ушёл:", e));
  убрать(скорость);
}

$("yes").addEventListener("click", () => {
  if (вопрос === "unmute") return ответить_про_микрофон(true);
  if (встреча?.mode === "join") return зайти(true);
  // Классика и «Записать» по встрече: машина во взводе, это подтверждение.
  ответить("confirm");
});
$("more").addEventListener("click", () => ($("pmenu").hidden ? открыть_меню() : закрыть_меню()));
$("join-only").addEventListener("click", () => зайти(false));

// Время вышло — вопрос уезжает молча. Это НЕ ответ, в отличие от смахивания:
// запись не начинается, но и отказа не было — состояние «взвод» остаётся, и
// вопрос по-прежнему доступен в главном окне и в трее. Разница намеренная:
// не заметить вопрос и отказаться от него — разные вещи.
$("life").addEventListener("animationend", () => убрать());

// Наведение. Считает его Rust по положению курсора и присылает готовым
