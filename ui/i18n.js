// Загрузчик локализации — обычный скрипт (НЕ модуль), подключается в обоих
// окнах ПЕРВЫМ, раньше main.js и ask.js. Единственный источник текстов —
// i18n/strings.json (ui/i18n/strings.json), его же вшивает себе Rust через
// include_str!: подстановки в фигурных скобках и назначение ключей описаны
// прямо там, в комментарии "_".
//
// Выставляет глобальный window.i18n = { ready, t, applyStatic, lang }.
// `ready` — промис, который резолвится, когда словарь загружен и язык
// определён; вызывающий код обязан его дождаться до первой отрисовки текста.
(function () {
  let словарь = null;
  let язык = "ru";

  // Порядок: явный выбор языка в конфиге приложения ("ru" | "en"), а если там
  // "system" или поле пустое — по языку системы (navigator.language).
  function определить_язык(из_конфига) {
    if (из_конфига === "ru" || из_конфига === "en") return из_конфига;
    return String(navigator.language || "").toLowerCase().startsWith("ru") ? "ru" : "en";
  }

  function подставить(строка, params) {
    if (!params) return строка;
    return строка.replace(/\{(\w+)\}/g, (совпадение, имя) =>
      Object.prototype.hasOwnProperty.call(params, имя) ? params[имя] : совпадение,
    );
  }

  // Ключ без ключа не роняет приложение: возвращаем сам ключ и предупреждаем
  // в консоль — так недостающая строка видна разработчику, но не пользователю.
  function t(ключ, params) {
    const [раздел, имя] = String(ключ).split(".");
    const запись = словарь?.[раздел]?.[имя];
    const строка = запись ? запись[язык] : null;
    if (строка == null) {
      console.warn(`i18n: нет строки для ключа "${ключ}"`);
      return String(ключ);
    }
    return подставить(строка, params);
  }

  // Обе языковые версии строки разом — редким местам, которые сравнивают
  // чужой текст со словарной строкой независимо от того, на каком языке
  // сейчас открыт интерфейс (например, суффикс "(сейчас недоступен)"/
  // "(currently unavailable)", который нужно снять с имени устройства вне
  // зависимости от текущего языка).
  function tBoth(ключ) {
    const [раздел, имя] = String(ключ).split(".");
    const запись = словарь?.[раздел]?.[имя];
    return { ru: запись?.ru ?? null, en: запись?.en ?? null };
  }

  function применить_к_узлу(el) {
    const ключ = el.getAttribute("data-i18n");
    if (ключ) el.textContent = t(ключ);
    const атрибуты = el.getAttribute("data-i18n-attr");
    if (!атрибуты) return;
    // Формат: "title:раздел.ключ" или несколько пар через ";" —
    // "title:раздел.ключ;aria-label:раздел.другой".
    for (const пара of атрибуты.split(";")) {
      const [атрибут, ключ_атрибута] = пара.split(":").map((s) => s.trim());
      if (атрибут && ключ_атрибута) el.setAttribute(атрибут, t(ключ_атрибута));
    }
  }

  // Проходит по всей статичной разметке и заполняет data-i18n / data-i18n-attr.
  // Динамические подписи (те, что зависят от состояния машины) ставит сам
  // main.js/ask.js через t() — applyStatic их не трогает.
  function applyStatic() {
    for (const el of document.querySelectorAll("[data-i18n], [data-i18n-attr]")) {
      применить_к_узлу(el);
    }
    document.documentElement.lang = язык;
  }

  async function загрузить() {
    let из_конфига = null;
    try {
      // window.__TAURI__ выставлен синхронно (withGlobalTauri: true), но код
      // должен пережить и запуск вне Tauri (например, открытие файла в
      // обычном браузере при вёрстке) — тогда конфига нет, и это не беда:
      // язык решится по navigator.language.
      из_конфига = (await window.__TAURI__?.core?.invoke("get_config"))?.language ?? null;
    } catch {
      // Конфиг не прочитался — решаем по системному языку.
    }
    язык = определить_язык(из_конфига);
    document.documentElement.lang = язык;
    const ответ = await fetch("i18n/strings.json");
    словарь = await ответ.json();
  }

  // Переключить язык без перезагрузки страницы: словарь уже загружен и
  // повторный fetch ему не нужен, меняется только то, какую половину каждой
  // записи возвращает t(). Вызывающий код (см. `ui/main.js`) отвечает за то,
  // чтобы после этого перерисовать всё, что уже показано на экране, — сам
  // setLang ничего на странице не трогает, кроме `<html lang>`.
  function setLang(из_конфига) {
    язык = определить_язык(из_конфига);
    document.documentElement.lang = язык;
    return язык;
  }

  window.i18n = {
    ready: загрузить(),
    t,
    tBoth,
    applyStatic,
    setLang,
    get lang() {
      return язык;
    },
  };
})();
