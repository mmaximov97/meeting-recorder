// Меню «⋯»
//
// Открытое меню живёт ровно одно: второе поверх первого — это два ответа на
// один вопрос.
let открытое_меню = null;

// `мгновенно` — когда список всё равно перерисовывается целиком и анимировать
// уже нечего: узел вот-вот исчезнет вместе со своей строкой.
function закрыть_меню(вернуть_фокус, мгновенно) {
  if (!открытое_меню) return;
  const { узел, строка, кнопка } = открытое_меню;
  открытое_меню = null;
  строка.classList.remove("open");
  if (мгновенно) {
    узел.remove();
  } else {
    узел.classList.add("закрывается");
    // Убираем по концу перехода, а не по таймеру-на-глаз: длительность живёт
    // в стилях, и разъехаться этим двум значениям нельзя.
    узел.addEventListener("transitionend", () => узел.remove(), { once: true });
    // Страховка на случай, если перехода не случилось вовсе (человек попросил
    // систему поменьше двигать — там длительность близка к нулю и события
    // может не быть).
    setTimeout(() => узел.remove(), 400);
  }
  if (вернуть_фокус) кнопка.focus();
  // Пока меню было открыто, про эту запись могли прийти новости — теперь
  // строку можно наконец пересобрать.
  if (список_ждёт_меню) {
    список_ждёт_меню = false;
    обновить_список();
  }
}

document.addEventListener("click", (e) => {
  if (открытое_меню && !открытое_меню.узел.contains(e.target) && e.target !== открытое_меню.кнопка) {
    закрыть_меню(false);
  }
});
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") закрыть_меню(true);
});

function пункт_меню(разметка, подпись, действие) {
  const b = document.createElement("button");
  b.append(значок(разметка), document.createTextNode(подпись));
  b.addEventListener("click", () => {
    закрыть_меню(false);
    действие();
  });
  return b;
}

// Состав меню зависит от состояния записи: первым пунктом стоит то, зачем его
// обычно открывают, а всё, что отменяет или переделывает уже сделанное, уходит
// под разделитель — даже если это самый вероятный клик.
function собрать_меню(запись, узел_имени) {
  const меню = document.createElement("div");
  меню.className = "menu";
  const ключ = ключ_транскрипции(запись.folder, запись.name);
  const стадия = транскрипции.get(ключ);
  const идёт = стадия_идёт(стадия) || стадия?.startsWith("queued:");
  const пара = запись.mic && запись.system;

  // Первым пунктом — то, зачем меню обычно открывают у расшифрованной записи.
  if (запись.transcript) {
    меню.append(
      пункт_меню(ЗНАЧКИ.документ, "Открыть расшифровку", () =>
        invoke("open_recording_folder", {
          folder: запись.folder ?? null,
          base: запись.name,
          transcript: true,
        }).catch((e) =>
          показать_ошибку(
            "Расшифровка не открылась. Найдите её через «Показать файлы».",
            e,
          ),
        ),
      ),
    );
  }

  меню.append(
    пункт_меню(ЗНАЧКИ.карандаш, "Переименовать", () =>
      начать_переименование(запись, узел_имени),
    ),
  );

  // Расшифровка возможна только у полной пары дорожек: одну без второй шлюзу
  // отдавать нечего склеивать.
  if (пара && !запись.transcript && !идёт) {
    меню.append(
      пункт_меню(ЗНАЧКИ.документ, "Расшифровать встречу", () => начать_транскрипцию(запись)),
    );
  }

  const низ = [];
  if (идёт) {
    низ.push(
      пункт_меню(ЗНАЧКИ.крестик, "Отменить расшифровку", () =>
        invoke("cancel_transcription", {
          folder: запись.folder ?? null,
          base: запись.name,
        }).catch((e) =>
          показать_ошибку("Отмена не сработала — расшифровка идёт дальше.", e),
        ),
      ),
    );
  }
  if (пара && запись.transcript && !идёт) {
    низ.push(пункт_меню(ЗНАЧКИ.заново, "Расшифровать заново", () => начать_транскрипцию(запись)));
  }
  // Папка самой записи, а не общий корень: пункт открыт из меню конкретной
  // строки, и приводить в каталог с полусотней чужих файлов — не то, о чём
  // просили.
  низ.push(
    пункт_меню(ЗНАЧКИ.папка, "Показать файлы", () =>
      invoke("open_recording_folder", {
        folder: запись.folder ?? null,
        base: запись.name,
        transcript: false,
      }).catch((e) =>
        показать_ошибку("Папка с записями не открылась. Попробуйте ещё раз.", e),
      ),
    ),
  );

  const разделитель = document.createElement("div");
  разделитель.className = "sep";
  меню.append(разделитель, ...низ);

  const подвал = document.createElement("small");
  if (идёт) {
    подвал.className = "plain";
    // Говорим, почему пункта «Расшифровать» нет: меню без объяснения читается
    // как поломка, а не как «нельзя».
    подвал.textContent = "Расшифровка уже идёт";
  } else {
    const аномалия = папка_аномальна(запись);
    подвал.textContent = аномалия ? `${аномалия} / ${запись.name}` : запись.name;
    подвал.title = подвал.textContent;
  }
  меню.append(подвал);
  return меню;
}

function открыть_меню(запись, строка, кнопка, узел_имени) {
  const было = открытое_меню?.кнопка === кнопка;
  закрыть_меню(false);
  if (было) return;
  // Меню предыдущего открытия могло ещё доигрывать закрытие в этой же строке —
  // два наложенных меню выглядели бы двоением.
  for (const прежнее of строка.querySelectorAll(".menu")) прежнее.remove();
  const узел = собрать_меню(запись, узел_имени);
  узел.classList.add("закрывается");
  строка.append(узел);
  строка.classList.add("open");
  // Заставляем движок посчитать стартовое состояние: без этого он схлопнет
  // добавление и снятие класса в один кадр, и перехода не будет вовсе.
  void узел.offsetHeight;
  узел.classList.remove("закрывается");
  открытое_меню = { узел, строка, кнопка };
  узел.querySelector("button")?.focus();
}

// Ключи записей, которые в этом окне уже показывались. Нужны затем, чтобы
// каскад появления играл ТОЛЬКО у новых строк. Окно живёт в трее и
// открывается по многу раз за день: каскад при каждом открытии из приятного
// становится назойливым и заставляет ждать. А вот запись, появившаяся после
// встречи, — событие редкое, и показать её стоит.
let показанные = new Set();

// ─────────────────────────────────────────────────────────────────────────────
// Строка записи
//
// Предупреждение о том, что с записью что-то не так, никогда не прячется под
// наведение: под наведение уходит только нейтральное — вес файла и отметка
// «расшифровка готова». Человек пролистывает список и должен увидеть беду,
// не водя мышью по каждой строке.
// Бед у одной записи может быть несколько: звук записался плохо И расшифровка
// не доехала. Раньше здесь возвращалась первая попавшаяся, и вторая молча
// пропадала — а это ровно тот случай, когда вторая объясняет первую («вас
// слышно тише» — вот почему в расшифровке половины реплик нет).
//
// Порядок — по времени: сначала что случилось при записи, потом что случилось
// при расшифровке. Так это читается как история, а кнопка «попробовать снова»
// оказывается внизу, где на неё и жмут.
function беды_записи(запись, ошибка, ошибка_имени) {
  const список = [];
  if (!запись.system) {
    список.push({
      значок: ЗНАЧКИ.микрофон_выкл,
      заголовок: "Собеседников не слышно",
      текст:
        "Записан только ваш микрофон: похоже, приложению не разрешили писать звук системы. " +
        "Проверьте разрешение, иначе следующая запись выйдет такой же.",
    });
  } else if (!запись.mic) {
    список.push({
      значок: ЗНАЧКИ.микрофон_выкл,
      заголовок: "Вас не слышно",
      текст: "Записан только звук системы, вашего микрофона в записи нет. Проверьте его в настройках.",
    });
  } else if (запись.imbalance_db != null) {
    список.push({
      значок: ЗНАЧКИ.микрофон_выкл,
      заголовок: "Вас слышно заметно тише",
      текст:
        "Ваш микрофон записался намного тише собеседников — расшифровка может пропустить ваши реплики. " +
        "Проверьте его в настройках перед следующей встречей.",
    });
  }
  if (ошибка) {
    список.push({
      значок: ЗНАЧКИ.облако_ошибка,
      заголовок: "Расшифровка не получилась",
      текст:
        "Запись цела — можно попробовать ещё раз или проверить адрес сервера в настройках.",
      подробность: ошибка,
      действие: "Попробовать снова",
      // Беда случилась от действия человека, а не была найдена при показе
      // списка: её появление надо озвучить (см. role="alert" ниже). У
      // предупреждений про качество записи этого флага нет — иначе скринридер
      // выкрикивал бы их при каждом открытии окна.
      тревога: true,
    });
  }
  // Переименование — тоже действие над конкретной записью, и его неудача
  // показывается в ней, а не общей строкой: «Permission denied» без указания
  // записи не говорит, какую из шести человек только что правил.
  if (ошибка_имени) {
    список.push({
      значок: ЗНАЧКИ.карандаш,
      заголовок: "Не удалось переименовать",
      текст: "Имя осталось прежним — попробуйте ещё раз.",
      подробность: ошибка_имени,
      тревога: true,
    });
  }
  return список;
}

function строка_записи(запись) {
  const li = document.createElement("li");
  li.className = "rec";

  const главное = document.createElement("div");
  главное.className = "main";

  const ист = источник(запись);
  const плашка = значок(
    ист.лого ? ЛОГОТИПЫ[ист.лого] : ЗНАЧКИ.микрофон,
    ист.лого ? `ava brand ${ист.лого}` : "ava",
  );

  const колонка = document.createElement("div");
  колонка.className = "col";
  const название = document.createElement("span");
  название.className = "title";
  название.textContent = ист.имя;
  // Название обрезается многоточием — полное отдаём подсказкой, иначе после
  // переименования его будет не прочитать.
  название.title = ист.имя;

  const ключ = ключ_транскрипции(запись.folder, запись.name);
  const стадия = транскрипции.get(ключ);
  const ошибка = ошибки_расшифровки.get(ключ);
  const ошибка_имени = ошибки_переименования.get(ключ);

  const мета = document.createElement("div");
  мета.className = "sub";
  if (стадия && стадия !== "done") {
    const детали = детали_расшифровки.get(ключ);
    const подпись =
      детали && стадия_идёт(стадия)
        ? `${подпись_стадии(стадия)} дорожка ${ДОРОЖКА_НОМЕР[детали.дорожка] ?? 1} из 2, ${сколько_идёт(детали.с)}`
        : подпись_стадии(стадия);
    мета.textContent = подпись;
  } else {
    мета.textContent = длительность(запись.duration_sec);
    const хвост = document.createElement("span");
    хвост.className = "more";
    хвост.textContent =
      ` · ${размер(запись.size)}` + (запись.transcript ? " · расшифровка готова" : "");
    мета.append(хвост);
  }
  колонка.append(название, мета);

  // Полоска неопределённая: сервер не сообщает процент, и врать процентом
  // нельзя. У записи в очереди её нет — ждать нечего показывать.
  if (стадия_идёт(стадия)) {
    const полоска = document.createElement("div");
    полоска.className = "prog";
    полоска.append(document.createElement("i"));
    колонка.append(полоска);
  }

  const справа = document.createElement("div");
  справа.className = "right";
  const время = document.createElement("span");
  время.className = "time";
  время.textContent = промежуток(момент_записи(запись.name), запись.duration_sec);
  const точки = document.createElement("span");
  точки.className = "dots";
  const кнопка = document.createElement("button");
  кнопка.setAttribute("aria-label", "Действия");
  кнопка.title = "Действия";
  кнопка.append(значок(ЗНАЧКИ.многоточие));
  кнопка.addEventListener("click", (e) => {
    e.stopPropagation();
    открыть_меню(запись, li, кнопка, название);
  });
  точки.append(кнопка);
  справа.append(время, точки);

  главное.append(плашка, колонка, справа);
  li.append(главное);

  const беды = беды_записи(запись, ошибка, ошибка_имени);
  if (беды.length) li.classList.add("card");
  for (const беда of беды) {
    const плашка_беды = document.createElement("div");
    плашка_беды.className = "note";
    // Живой областью помечается только то, что случилось от действия. Узел
    // с role="alert" озвучивается в момент попадания в документ — а плашки
    // про качество записи попадают туда при каждой отрисовке списка.
    if (беда.тревога) плашка_беды.setAttribute("role", "alert");
    const текст = document.createElement("span");
    текст.className = "nt";
    const заголовок = document.createElement("b");
    заголовок.textContent = беда.заголовок;
    текст.append(заголовок, document.createTextNode(беда.текст));
    if (беда.действие) {
      const кнопка_беды = document.createElement("button");
      кнопка_беды.className = "act";
      кнопка_беды.textContent = беда.действие;
      кнопка_беды.addEventListener("click", () => начать_транскрипцию(запись));
      текст.append(document.createElement("br"), кнопка_беды);
    }
    плашка_беды.append(значок(беда.значок, "ni"), текст);
    // Сырое сообщение из движка человеку не показывается — техническая причина
    // живёт в подсказке, то есть доступна тому, кто её ищет.
    if (беда.подробность) плашка_беды.title = беда.подробность;
    li.append(плашка_беды);
  }
  return li;
}

// Каскад ограничен шестью строками: дальше задержка становится ожиданием, а не
// украшением. 26мс между соседями — на грани заметности, и это то, что нужно:
// каскад должен ощущаться, а не разглядываться. Последняя строка при этом
// доезжает к 456мс (156 задержки + 300 самого въезда) — дольше уже начинает
// читаться как «список тормозит».
const ШАГ_КАСКАДА_МС = 26;
const МАКС_В_КАСКАДЕ = 6;

// ─────────────────────────────────────────────────────────────────────────────
// Список обновляется точечно
//
// Раньше здесь было list.innerHTML = "" и полная пересборка. Она стоила трёх
// вещей сразу: открытое меню «⋯» гасло, прокрутка прыгала, и весь список
// заметно моргал при каждом открытии окна из трея. А дёргается он часто —
// во время расшифровки события прогресса приходят по нескольку раз в секунду,
// и каждое перерисовывало все шесть записей ради одной изменившейся.
//
// Теперь узлы переиспользуются: строка пересобирается только тогда, когда в
// ней самой что-то поменялось, а порядок выправляется перестановкой.
const строки_списка = new Map(); // ключ записи -> { li, подпись }
const дни_списка = new Map(); // ярлык дня -> { заголовок, ul }

// Всё, что строка_записи читает из записи и карт состояния. Совпали подписи —
// строку можно оставить как есть.
function подпись_строки(з, ключ) {
  return JSON.stringify([
    з.name,
    з.folder,
    з.size,
    з.duration_sec,
    з.mic,
    з.system,
    з.transcript,
    з.imbalance_db,
    транскрипции.get(ключ) ?? null,
    ошибки_расшифровки.get(ключ) ?? null,
    ошибки_переименования.get(ключ) ?? null,
  ]);
}

// Ставит узлы под родителя в нужном порядке, трогая только те, что стоят не
// на своём месте. Уже стоящий правильно узел не переставляется вовсе — иначе
// он выпал бы из документа и вернулся, а это и есть моргание.
function выровнять(родитель, узлы) {
  let текущий = родитель.firstChild;
  for (const узел of узлы) {
    if (текущий === узел) {
      текущий = текущий.nextSibling;
      continue;
    }
    родитель.insertBefore(узел, текущий);
  }
  while (текущий) {
    const следующий = текущий.nextSibling;
    родитель.removeChild(текущий);
    текущий = следующий;
  }
}

// Класс въезда снимается сразу по окончании анимации. Раньше строку на каждой
// отрисовке создавали заново, и класс умирал вместе с ней; теперь узлы живут
// долго, и висящий класс держал бы `transform` под управлением анимации с
// `fill-mode: both`. Строка от этого становится отдельным слоем, и открытое в
// ней меню «⋯» не может подняться над строками ниже — они его перекрывают.
function въехать(узел, задержка) {
  узел.classList.add("новая");
  узел.style.setProperty("--задержка", задержка);
  узел.addEventListener(
    "animationend",
    () => {
      узел.classList.remove("новая");
      узел.style.removeProperty("--задержка");
    },
    { once: true },
  );
}

// Поле правки имени живёт в DOM, а не в данных записи, поэтому подпись_строки
// про него ничего не знает. Пересобрать строку «потому что данные изменились»
// тут нельзя: человек нажал Enter, не поменяв ни буквы, — бэкенд честно
// отвечает «уже так и называется», подпись прежняя, и поле с синей обводкой
// остаётся на экране навсегда. Забываем строку — и следующая отрисовка
// собирает её заново, уже без поля.
function забыть_строку(ключ) {
  const узел = строки_списка.get(ключ);
  // Не удаляем запись из карты, а портим подпись: сам узел ещё нужен, чтобы
  // подменить его в документе на месте. Настоящая подпись — строка из JSON,
  // равной null она не бывает никогда.
  if (узел) узел.подпись = null;
}

// Меню живёт внутри своей строки: если строку сейчас заменят или уберут, его
// надо закрыть руками — иначе оно исчезнет вместе с узлом, не вернув фокус.
function закрыть_меню_в(li) {
  if (открытое_меню?.строка === li) закрыть_меню(false, true);
}

// Строку с открытым меню не пересобираем. Меню — часть этой строки, и пересборка
// уносила его вместе с узлом: человек нажал «⋯», а оно закрылось само, стоило
// прилететь любому событию про эту запись. Данные подождут: перерисовка догонит,
// как только меню закроется.
let список_ждёт_меню = false;

function отрисовать_список(записи) {
  const list = $("list");
  $("empty").hidden = записи.length > 0;

  // Записи приходят от новых к старым (group_recordings сортирует по имени,
  // а имя начинается с даты), поэтому группировать можно подряд.
  const группы = [];
  for (const з of записи) {
    const день = ярлык_дня(момент_записи(з.name));
    if (!группы.length || группы[группы.length - 1].день !== день) {
      группы.push({ день, записи: [] });
    }
    группы[группы.length - 1].записи.push(з);
  }

  const было = показанные;
  показанные = new Set();
  let новых = 0;

  const порядок = [];
  const живые_дни = new Set();
  const живые_строки = new Set();

  for (const группа of группы) {
    живые_дни.add(группа.день);
    let узлы_дня = дни_списка.get(группа.день);
    if (!узлы_дня) {
      const заголовок = document.createElement("div");
      заголовок.className = "day";
      заголовок.textContent = группа.день;
      узлы_дня = { заголовок, ul: document.createElement("ul") };
      дни_списка.set(группа.день, узлы_дня);
    }
    порядок.push(узлы_дня.заголовок, узлы_дня.ul);

    const строки_дня = [];
    let первая_в_группе = true;
    for (const з of группа.записи) {
      const ключ = ключ_транскрипции(з.folder, з.name);
      живые_строки.add(ключ);
      показанные.add(ключ);
      const новая = !было.has(ключ);
      const подпись = подпись_строки(з, ключ);

      let узел = строки_списка.get(ключ);
      if (!узел || узел.подпись !== подпись) {
        if (узел && открытое_меню?.строка === узел.li) {
          // Подпись НЕ обновляем — иначе строка так и останется со старым
          // содержимым, когда меню закроется и перерисовка вернётся.
          список_ждёт_меню = true;
        } else {
          const li = строка_записи(з);
          // Подменяем узел прямо на его месте. Без этого выровнять() ниже
          // вставит новый перед старым и протащит через документ все строки,
          // стоящие следом, — а это ровно то моргание, от которого уходили.
          if (узел && узел.li.isConnected) узел.li.replaceWith(li);
          узел = { li, подпись };
          строки_списка.set(ключ, узел);
        }
      }

      if (новая) {
        const задержка = `${Math.min(новых, МАКС_В_КАСКАДЕ) * ШАГ_КАСКАДА_МС}ms`;
        въехать(узел.li, задержка);
        // Заголовок дня въезжает вместе со своей первой строкой, а не отдельно:
        // «Сегодня» без записи под ним висело бы в воздухе лишние треть секунды.
        if (первая_в_группе) въехать(узлы_дня.заголовок, задержка);
        новых++;
      }
      первая_в_группе = false;
      строки_дня.push(узел.li);
    }
    выровнять(узлы_дня.ul, строки_дня);
  }

  for (const [ключ, узел] of строки_списка) {
    if (живые_строки.has(ключ)) continue;
    закрыть_меню_в(узел.li);
    узел.li.remove();
    строки_списка.delete(ключ);
  }
  for (const [день, узлы] of дни_списка) {
    if (живые_дни.has(день)) continue;
    узлы.заголовок.remove();
    узлы.ul.remove();
    дни_списка.delete(день);
  }

  выровнять(list, порядок);
}

// Пока открыто поле правки имени, список не перерисовывается вовсе. Причина
// не в мигании: перерисовка выбрасывала из документа ещё сфокусированное
// поле, а выброс сфокусированного узла сам порождает blur — и недописанное
// имя уезжало на диск. Отложенная перерисовка догоняет сразу по закрытии поля.
let правка_идёт = false;
let список_ждёт_правку = false;

function отложить_список() {
  список_ждёт_правку = true;
}

// Поле правки закрылось — заморозка снимается, и отложенное обновление
// догоняет сразу же. Обе стороны (применить и отменить) следом сами зовут
// обновить_список, поэтому здесь только снимаем флаги.
function закрыть_правку() {
  правка_идёт = false;
  список_ждёт_правку = false;
}

// Ответы приходят не в том порядке, в каком уходили запросы: во время
// расшифровки список дёргается по нескольку раз в секунду, и старый ответ,
// доехавший последним, откатил бы экран назад.
let поколение_списка = 0;

async function обновить_список() {
  if (правка_идёт) return отложить_список();
  const моё = ++поколение_списка;
  let записи;
  try {
    записи = await invoke("list_recordings");
  } catch (e) {
    $("skeleton").hidden = true;
    показать_ошибку("Список записей не прочитался. Закройте окно и откройте его снова из трея.", e);
    return;
  }
  if (моё !== поколение_списка) return;
  if (правка_идёт) return отложить_список();
  // Скелетон уходит навсегда: дальше список обновляется точечно, и подменять
  // готовые строки заглушками было бы враньём.
  $("skeleton").hidden = true;
  отрисовать_список(записи);
}

// Префикс с датой не редактируется: по нему идёт сортировка списка, склейка
// пары дорожек и выбор месячной папки. Поле правит только хвост.
//
// И не показывается тоже. Раньше `2026-08-26_16-00_` стояло перед полем и
// занимало половину строки, отжимая вправо ровно то единственное, что человек
// пришёл менять. Дата от этого никуда не делась: она в имени файла на диске и
// в подвале меню «⋯», где ей и место.
function начать_переименование(запись, узел_имени) {
  const хвост = запись.name.slice(ДЛИНА_ПРЕФИКСА);
  узел_имени.textContent = "";
  // Снимает обрезку многоточием на время правки: иначе поле ввода, шириной во
  // весь контейнер, срезается `overflow` — и выглядит это как исчезнувшее
  // место ввода. Класс не убираем — `обновить_список` пересобирает строку
  // целиком.
  узел_имени.classList.add("editing");
  // Полное имя в подсказке относится к обычному состоянию; в режиме правки оно
  // только мешает, перекрывая поле всплывашкой.
  узел_имени.removeAttribute("title");
  const ключ = ключ_транскрипции(запись.folder, запись.name);
  // Прошлая неудача относится к прошлой попытке: держать её на экране, пока
  // человек уже правит имя заново, значит показывать «не получилось» над
  // открытым полем ввода.
  ошибки_переименования.delete(ключ);

  const поле = document.createElement("input");
  поле.className = "tail-input";
  поле.value = хвост;
  // Одно поле правки на весь список: пока оно открыто, обновить_список не
  // перерисовывает ничего, и второе открытое поле означало бы, что первое
  // уже никто не закроет.
  правка_идёт = true;
  узел_имени.append(поле);
  поле.focus();
  поле.select();

  // Флаг и снятие слушателя защищают от тройного срабатывания и остаются на
  // месте, хотя перерисовка теперь и не может выбросить поле из документа
  // (правка_идёт её замораживает). Без них это било так: Escape вместо
  // отмены применял текущее значение поля через blur-обработчик, обычное
  // применение через Enter задваивалось тем же blur'ом, а быстрый повторный
  // Enter или Tab до ответа сервера давал второй invoke. Первые два случая
  // отпали вместе с применением по blur, третий — нет.
  let завершено = false;

  const отписаться = () => поле.removeEventListener("blur", на_потерю_фокуса);

  const применить = async () => {
    if (завершено) return;
    завершено = true;
    отписаться();
    поле.disabled = true;
    // Флаги снимаем здесь, а не после ответа: значение уже забрано, поле
    // выключено, и перерисовке больше нечего ломать. Ждать ответа значило бы
    // держать список замороженным всё время похода на диск.
    закрыть_правку();
    забыть_строку(ключ);
    try {
      await invoke("rename_recording", {
        folder: запись.folder ?? null,
        base: запись.name,
        newTail: поле.value,
      });
    } catch (e) {
      // Не получилось у конкретной записи — и показывается это в ней:
      // строка ниже пересоберётся с плашкой «Не удалось переименовать».
      ошибки_переименования.set(ключ, String(e));
    }
    обновить_список();
  };

  const отменить = () => {
    if (завершено) return;
    завершено = true;
    отписаться();
    закрыть_правку();
    забыть_строку(ключ);
    обновить_список();
  };

  // Клик мимо СОХРАНЯЕТ — так ведут себя Finder и все остальные места, где
  // имя правят прямо в строке, и другого человек не ждёт. Escape отменяет.
  //
  // Раньше сохранение по blur было опасным, но не поэтому: перерисовка списка
  // выбрасывала сфокусированное поле из документа, а выброс сфокусированного
  // узла сам порождает blur — и на диск уезжало недописанное имя от чужого
  // тика расшифровки. Эта причина ушла: пока поле открыто, список заморожен
  // (правка_идёт). Оба условия ниже стерегут остаток.
  const на_потерю_фокуса = () => {
    // Окно ушло в фон — переключились на браузер, нажали хоткей. Это не «клик
    // мимо»: правку держим открытой, человек вернётся и допишет.
    if (!document.hasFocus()) return;
    // Поле уже не в документе — значит blur породил не человек, а код.
    // Сохранять по такому blur'у нечего.
    if (!document.contains(поле)) return;
    применить();
  };

  поле.addEventListener("keydown", (e) => {
    if (e.key === "Enter") применить();
    if (e.key === "Escape") отменить();
    // Меню уже закрыто, но Escape всплывает до общего обработчика и там ничего
    // не делает — сюда он приходит первым, отменяя правку.
    e.stopPropagation();
  });
  поле.addEventListener("blur", на_потерю_фокуса);
}

async function начать_транскрипцию(запись) {
  const ключ = ключ_транскрипции(запись.folder, запись.name);
  // Прошлая ошибка относится к прошлой попытке: оставить её на экране значит
  // показывать «не получилось» рядом с полоской «идёт».
  ошибки_расшифровки.delete(ключ);
  детали_расшифровки.delete(ключ);
  // Стадию ставим сами, не дожидаясь бэкенда: до первого события прогресса
  // проходит заметное время, и всё это время строка выглядела нетронутой —
  // человек открывал меню и жал «Расшифровать» второй раз. С этой строкой
  // мета сразу становится «Расшифровываю…», под ней едет полоска, а пункта
  // «Расшифровать встречу» в меню больше нет.
  const своя_стадия = транскрипции.get(ключ) == null;
  if (своя_стадия) транскрипции.set(ключ, СТАДИЯ_ЗАПУСК);
  обновить_список();
  try {
    await invoke("transcribe_recording", { folder: запись.folder ?? null, base: запись.name });
  } catch (e) {
    // Снимаем только свою стадию: настоящее событие прогресса могло прийти
    // раньше отказа, и затирать его нельзя.
    if (транскрипции.get(ключ) === СТАДИЯ_ЗАПУСК) транскрипции.delete(ключ);
    ошибки_расшифровки.set(ключ, String(e));
    обновить_список();
  }
}

