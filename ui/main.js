// Настройки
//
// Значение <option> — идентификатор эндпоинта, подпись — имя. Пользователь
// выбирает глазами по имени, приложение запоминает идентификатор: имя может
// поменяться в настройках Windows, идентификатор — нет.
async function обновить_устройства() {
  try {
    const [устройства, конфиг] = await Promise.all([
      invoke("list_mic_devices"),
      invoke("get_config"),
    ]);
    const sel = $("mic");
    sel.innerHTML = "";
    const дефолт = document.createElement("option");
    дефолт.value = "";
    дефолт.textContent = "Как выбрано в системе";
    sel.append(дефолт);
    for (const у of устройства) {
      const o = document.createElement("option");
      o.value = у.id;
      o.textContent = у.name;
      sel.append(o);
    }
    // Сохранённое устройство может отсутствовать прямо сейчас (гарнитура
    // выключена) — тогда его вообще нет среди `устройства`, и `sel.value`
    // ниже просто не находит совпадения: браузер откатывает выпадашку на
    // первый пункт, «Системный по умолчанию». Саму настройку это не трогает —
    // `set_mic_device` шлётся только по явному `change` пользователем
    // (см. ниже), а не потому что список перерисовался; если гарнитуру
    // включат обратно, `обновить_устройства` (по фокусу окна или
    // `devicechange`) снова найдёт её в списке и подсветит как выбранную.
    // О том, что запись реально пишется не тем устройством, отдельно
    // предупреждает баннер `#devwarn` — он держит это состояние честно,
    // а не выпадашка.
    const сохранён = конфиг.mic_device_id ?? "";
    sel.value = сохранён;
    // Пока смена отложена, в конфиге уже НОВЫЙ микрофон, а подписи нужен тот,
    // которым пишется идущая запись, — поэтому здесь не трогаем.
    if (!смена_отложена) сохранённый_микрофон = конфиг.mic_device_name ?? null;
    $("stt-url").value = конфиг.stt_gateway_url ?? "";
    $("stt-key").value = конфиг.stt_api_key ?? "";
  } catch (e) {
    показать_ошибку("Не вижу микрофонов. Откройте настройки заново.", e);
  }
}

// Подтверждение сохранения — строка рядом с тем, что сохранили, не тост и не
// модалка. Мест таких два: под полями расшифровки и под выпадашкой микрофона.
// Тост в углу окна тут не годится — он одинаково далеко от обоих.
const таймеры_сохранено = new Map();

function показать_сохранено(id) {
  const el = $(id);
  el.hidden = false;
  // Перезапуск анимации: второе сохранение подряд иначе не мигнёт, и человек
  // не поймёт, что оно вообще случилось второй раз.
  el.style.animation = "none";
  void el.offsetHeight;
  el.style.animation = "";
  clearTimeout(таймеры_сохранено.get(id));
  таймеры_сохранено.set(
    id,
    setTimeout(() => {
      el.hidden = true;
      таймеры_сохранено.delete(id);
    }, 2500),
  );
}

