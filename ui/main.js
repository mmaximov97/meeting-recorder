let проверка_идёт = false;

$("check").addEventListener("click", async () => {
  const включаем = !проверка_идёт;
  // Кнопка гаснет и меняет подпись по клику, а не когда придут уровни: между
  // кликом и первым событием проходит до нескольких сотен миллисекунд, и всё
  // это время экран выглядел нетронутым. При выключении событий может не
  // прийти вовсе — тогда подпись так и осталась бы прежней.
  $("check").disabled = true;
  $("check").textContent = включаем ? "Включаю…" : "Останавливаю…";
  try {
    await invoke("set_monitor", { on: включаем });
    // Ответ команды — и есть подтверждение: дальше подпись держит
    // применить_уровни по событиям, но первое из них может задержаться.
    проверка_идёт = включаем;
    показать_ошибку("");
  } catch (e) {
    показать_ошибку(
      включаем
        ? "Проверка не включилась. Посмотрите, не занят ли микрофон другой программой."
        : "Проверка не выключилась. Она погаснет сама через минуту.",
      e,
    );
  } finally {
    $("check").disabled = false;
    $("check").textContent = проверка_идёт ? "Остановить проверку" : "Проверить";
  }
});

// Ядро отдаёт линейный пик 0..1 — это физическая амплитуда, и её умышленно
// не трогаем: на macOS этим же числом (`app.levels()`) гейтится детект
// звонка по звуку (`audio.rs::detect.step`), и калибровать там нужно линейный
// пик, а не то, как он выглядит в полоске. В линейном виде это же число почти
// всегда «пустая» полоска: нормальная речь на здоровом уровне записи редко
// превышает четверть-треть от полного размаха, а не половину. Переводим в
// дБFS и показываем от -60 дБ (тихо, но видно шевеление) до 0 дБ (потолок,
// клиппинг) — тот же диапазон, что у большинства аудиоредакторов и микшеров.
const МЕТР_ПОЛ_ДБ = -60;

// Держим пик секунду как есть, потом отпускаем на ~20 дБ/с — обычная скорость
// спада у peak-hold в аудиоредакторах. Событие "levels" шлётся раз в 200мс
// (audio.rs::TICK), поэтому спад считаем не таймером, а на каждый тик.
const ПИК_УДЕРЖАНИЕ_МС = 1000;
const ПИК_СПАД_ДБ_ЗА_ТИК = 4;

// db == null значит «сигнала не было ни разу с последнего сброса» — отличаем
// от «сигнал был, но спал до пола», иначе после сброса маркер сразу лежал бы
// на -60 дБ вместо того, чтобы быть невидимым до первого звука.
const пик = {
  mic: { db: null, момент: 0 },
  system: { db: null, момент: 0 },
};

function сбросить_пики() {
  пик.mic.db = null;
  пик.system.db = null;
}

function линейный_в_дб(линейный) {
  if (линейный <= 0) return null;
  return Math.max(МЕТР_ПОЛ_ДБ, 20 * Math.log10(линейный));
}

function дб_в_проценты(db) {
  return Math.min(100, Math.max(0, ((db - МЕТР_ПОЛ_ДБ) / -МЕТР_ПОЛ_ДБ) * 100));
}

// Ядро отдаёт линейный пик 0..1 — это физическая амплитуда, и её умышленно
// не трогаем: на macOS этим же числом (`app.levels()`) гейтится детект
// звонка по звуку (`audio.rs::detect.step`), и калибровать там нужно линейный
// пик, а не то, как он выглядит в полоске. В линейном виде это же число почти
// всегда «пустая» полоска: нормальная речь на здоровом уровне записи редко
// превышает четверть-треть от полного размаха, а не половину. Переводим в
// дБFS и показываем от -60 дБ (тихо, но видно шевеление) до 0 дБ (потолок,
// клиппинг) — тот же диапазон, что у большинства аудиоредакторов и микшеров.
function уровень_в_проценты(линейный) {
  const db = линейный_в_дб(линейный);
  return db == null ? 0 : дб_в_проценты(db);
}

function обновить_пик(канал, линейный) {
  const состояние = пик[канал];
  const текущий_db = линейный_в_дб(линейный);
  const сейчас = Date.now();
  if (текущий_db != null && (состояние.db == null || текущий_db >= состояние.db)) {
    состояние.db = текущий_db;
    состояние.момент = сейчас;
  } else if (состояние.db != null && сейчас - состояние.момент > ПИК_УДЕРЖАНИЕ_МС) {
    состояние.db = Math.max(МЕТР_ПОЛ_ДБ, состояние.db - ПИК_СПАД_ДБ_ЗА_ТИК);
  }
  return состояние.db;
}

// Метров на экране два комплекта: полные в настройках и узкие в панели «идёт
// запись». Считается канал один раз, а рисуется в оба — поэтому не один узел,
// а выборка по data-атрибуту. Числа в децибелах человеку больше не
// показываются: «-18 дБ» ему ничего не говорит, а «доходить до середины и не
// залезать в красное» — говорит (подсказка под метрами в настройках).
function обновить_канал(канал, линейный) {
  const пиковый_db = обновить_пик(канал, линейный);
  const проценты = пиковый_db == null ? null : `${дб_в_проценты(пиковый_db)}%`;
  for (const маркер of document.querySelectorAll(`[data-peak="${канал}"]`)) {
    маркер.classList.toggle("on", пиковый_db != null);
    if (проценты != null) маркер.style.setProperty("--peak", проценты);
  }
}

function применить_уровни(l) {
  for (const канал of ["mic", "system"]) {
    const уровень = `${уровень_в_проценты(l[канал])}%`;
    for (const заливка of document.querySelectorAll(`[data-level="${канал}"]`)) {
      заливка.style.setProperty("--level", уровень);
    }
    обновить_канал(канал, l[канал]);
  }
  проверка_идёт = Boolean(l.monitoring);
  $("check").textContent = проверка_идёт ? "Остановить проверку" : "Проверить";
}

function размер(байты) {
  if (байты < 1024) return `${байты} Б`;
  const кб = байты / 1024;
  if (кб < 1024) return `${кб.toFixed(0)} КБ`;
  const мб = кб / 1024;
  // Десятая доля мегабайта при таком масштабе не значит ничего, а «1720.2 МБ»
  // ещё и плохо читается. От гигабайта один знак возвращаем — там он различим.
  return мб < 1024 ? `${Math.round(мб)} МБ` : `${(мб / 1024).toFixed(1).replace(".", ",")} ГБ`;
}

// Папка выводится в подвале меню записи, только если противоречит дате в имени.
// При совпадении она буквально повторяет первые семь символов имени, стоящего
// строкой выше, — информации ноль, место занято. Несовпадение же означает, что
// запись лежит не там: осталась в корне после незавершённой миграции или её
// двигали руками. Тогда это единственный признак, что стоит присмотреться.
function папка_аномальна(запись) {
  if (запись.folder == null) return "в корне";
  return запись.folder === запись.name.slice(0, 7) ? null : запись.folder;
}

// ─────────────────────────────────────────────────────────────────────────────
// Имя записи → источник, название и время
//
// Имя файла собирается как `<дата>_<время>_<источник>` (src/storage.rs), где
// источник — очищенное имя процесса. После переименования хвост становится
// произвольным, поэтому узнавание работает как «совпало — показываем логотип,
// не совпало — показываем то, что человек написал».
const ДЛИНА_ПРЕФИКСА = 17;

// Ключи — источник ИЗ ИМЕНИ ФАЙЛА, после `sanitize_source`
// (`src/storage.rs:124`). Это исторический словарь: имена на диске не
// переименовываются, поэтому здесь обязаны жить оба написания — macOS
// (`zoom-us`) и Windows (`zoom`, `ms-teams`, `teams`), — иначе у записей,
// сделанных на другой системе, пропадёт логотип. Живые идентификаторы
// звонилок — в `ui/ask.js`, это другая таблица и другой формат.
//
