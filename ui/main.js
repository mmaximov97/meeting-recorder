// Ядро отдаёт линейный пик 0..1 — это физическая амплитуда, и её умышленно
// не трогаем: на macOS этим же числом (`app.levels()`) гейтится детект
// звонка по звуку (`audio.rs::detect.step`), и калибровать там нужно линейный
// пик, а не то, как он выглядит в полоске. В линейном виде это же число почти
// всегда «пустая» полоска: нормальная речь на здоровом уровне записи редко
// превышает четверть-треть от полного размаха, а не половину. Переводим в
// дБFS и показываем от -60 дБ (тихо, но видно шевеление) до 0 дБ (потолок,
// клиппинг) — тот же диапазон, что у большинства аудиоредакторов и микшеров.
const МЕТР_ПОЛ_ДБ = -60;

// Держим пик секунду как есть, потом отпускаем на ~20 дБ/с — обычная скорость
// спада у peak-hold в аудиоредакторах. Событие "levels" шлётся раз в 200мс
// (audio.rs::TICK), поэтому спад считаем не таймером, а на каждый тик.
const ПИК_УДЕРЖАНИЕ_МС = 1000;
const ПИК_СПАД_ДБ_ЗА_ТИК = 4;

// db == null значит «сигнала не было ни разу с последнего сброса» — отличаем
// от «сигнал был, но спал до пола», иначе после сброса маркер сразу лежал бы
// на -60 дБ вместо того, чтобы быть невидимым до первого звука.
const пик = {
  mic: { db: null, момент: 0 },
  system: { db: null, момент: 0 },
};

function сбросить_пики() {
  пик.mic.db = null;
  пик.system.db = null;
}

function линейный_в_дб(линейный) {
  if (линейный <= 0) return null;
  return Math.max(МЕТР_ПОЛ_ДБ, 20 * Math.log10(линейный));
}

function дб_в_проценты(db) {
  return Math.min(100, Math.max(0, ((db - МЕТР_ПОЛ_ДБ) / -МЕТР_ПОЛ_ДБ) * 100));
}

// Ядро отдаёт линейный пик 0..1 — это физическая амплитуда, и её умышленно
// не трогаем: на macOS этим же числом (`app.levels()`) гейтится детект
// звонка по звуку (`audio.rs::detect.step`), и калибровать там нужно линейный
// пик, а не то, как он выглядит в полоске. В линейном виде это же число почти
// всегда «пустая» полоска: нормальная речь на здоровом уровне записи редко
// превышает четверть-треть от полного размаха, а не половину. Переводим в
// дБFS и показываем от -60 дБ (тихо, но видно шевеление) до 0 дБ (потолок,
// клиппинг) — тот же диапазон, что у большинства аудиоредакторов и микшеров.
function уровень_в_проценты(линейный) {
  const db = линейный_в_дб(линейный);
  return db == null ? 0 : дб_в_проценты(db);
}

function обновить_пик(канал, линейный) {
  const состояние = пик[канал];
  const текущий_db = линейный_в_дб(линейный);
  const сейчас = Date.now();
  if (текущий_db != null && (состояние.db == null || текущий_db >= состояние.db)) {
    состояние.db = текущий_db;
    состояние.момент = сейчас;
  } else if (состояние.db != null && сейчас - состояние.момент > ПИК_УДЕРЖАНИЕ_МС) {
    состояние.db = Math.max(МЕТР_ПОЛ_ДБ, состояние.db - ПИК_СПАД_ДБ_ЗА_ТИК);
  }
  return состояние.db;
}

// Метров на экране два комплекта: полные в настройках и узкие в панели «идёт
// запись». Считается канал один раз, а рисуется в оба — поэтому не один узел,
// а выборка по data-атрибуту. Числа в децибелах человеку больше не
// показываются: «-18 дБ» ему ничего не говорит, а «доходить до середины и не
// залезать в красное» — говорит (подсказка под метрами в настройках).
function обновить_канал(канал, линейный) {
  const пиковый_db = обновить_пик(канал, линейный);
  const проценты = пиковый_db == null ? null : `${дб_в_проценты(пиковый_db)}%`;
  for (const маркер of document.querySelectorAll(`[data-peak="${канал}"]`)) {
    маркер.classList.toggle("on", пиковый_db != null);
    if (проценты != null) маркер.style.setProperty("--peak", проценты);
  }
  return пиковый_db == null ? null : дб_в_проценты(пиковый_db);
}

// Собеседников не слышно: звук системы не пишется вовсе (баннер
// «Звук системы не пишется») или дорожка молчит дольше ТИШИНА_МС подряд во
// время записи. Порог -50 дБ — ниже обычного шума комнаты в звонке.
const ТИШИНА_МС = 10000;
const ТИШИНА_ЛИНЕЙНО = 0.003;
let тишина_с = null;

function отметить_тишину(линейный) {
  if (предыдущее_состояние !== "recording") {
    тишина_с = null;
    return;
  }
  if ((линейный ?? 0) >= ТИШИНА_ЛИНЕЙНО) тишина_с = null;
  else if (тишина_с == null) тишина_с = Date.now();
  if (показано_молчат !== собеседники_молчат()) отрисовать_пульт();
}

// Что сейчас нарисовано на пульте — перерисовываем только при смене.
let показано_молчат = false;

function собеседники_молчат() {
  if (нет_системного_звука) return true;
  return тишина_с != null && Date.now() - тишина_с >= ТИШИНА_МС;
}

// Пульт: название встречи — идущая встреча из календаря, иначе звонилка,
// иначе «Запись»; справа сервис; ниже «Потом» — следующая встреча сегодня.
function отрисовать_пульт() {
  if (предыдущее_состояние !== "recording") return;
  const сейчас = Date.now();
  const встречи = календарь?.auth === "connected" ? (календарь.today ?? []) : [];
  const идёт = встречи.find((в) => в.start_ms <= сейчас + 5 * 60000 && в.end_ms > сейчас);
  const следующая = встречи.find((в) => в !== идёт && в.start_ms > сейчас);
  const имя_звонилки = ЗВОНИЛКИ[звонилка_записи] ?? звонилка_записи;
  $("rec-name").textContent =
    идёт?.title?.trim() || имя_звонилки || i18n.t("record.manualName");
  $("rec-src").textContent = идёт ? (СЕРВИСЫ[идёт.source] ?? "") : "";
  $("pult-then").hidden = !следующая;
  if (следующая) {
    $("then-time").textContent = чч_мм(new Date(следующая.start_ms));
    $("then-title").textContent = следующая.title?.trim() || i18n.t("calendar.untitled");
  }
  const молчат = собеседники_молчат();
  показано_молчат = молчат;
  $("lb-them").textContent = i18n.t(молчат ? "levels.othersSilent" : "levels.others");
  $("lb-them").classList.toggle("bad", молчат);
  $("pult-warn").hidden = !молчат;
}

// ─────────────────────────────────────────────────────────────────────────────
// Сегментный индикатор уровня (`.leds`)
//
// Переиспользуемый: проверка микрофона в настройках, дальше — пульт записи.
// Разметка — пустой `<span class="leds" data-leds="mic|system" data-n="24">`,
// сегменты строит `собрать`. Цвет сегмента задан его местом на шкале, как у
// полоски `.disc`: до 70% (-18 дБ) зелёный, до 90% (-6 дБ) жёлтый, дальше
// красный. Горят сегменты до текущего уровня и один — на пике.
const сегменты = {
  собрать(узел) {
    if (узел.childElementCount) return;
    const n = Number(узел.dataset.n) || 24;
    узел.style.setProperty("--n", n);
    for (let i = 0; i < n; i++) {
      const место = ((i + 0.5) / n) * 100;
      const с = document.createElement("i");
      с.className = место < 70 ? "g" : место < 90 ? "a" : "r";
      узел.append(с);
    }
  },
  показать(узел, проценты, пик_проценты) {
    сегменты.собрать(узел);
    const всего = узел.children.length;
    const горит = Math.round((проценты / 100) * всего);
    const пик = пик_проценты == null ? -1 : Math.ceil((пик_проценты / 100) * всего) - 1;
    for (let i = 0; i < всего; i++) {
      узел.children[i].classList.toggle("on", i < горит || i === пик);
    }
  },
};

function применить_уровни(l) {
  for (const канал of ["mic", "system"]) {
    const проценты = уровень_в_проценты(l[канал]);
    const уровень = `${проценты}%`;
    for (const заливка of document.querySelectorAll(`[data-level="${канал}"]`)) {
      заливка.style.setProperty("--level", уровень);
    }
    const пик_проценты = обновить_канал(канал, l[канал]);
    if (канал === "system") отметить_тишину(l.system);
    for (const узел of document.querySelectorAll(`[data-leds="${канал}"]`)) {
      сегменты.показать(узел, проценты, пик_проценты);
    }
  }
  // Полоски рисуются всегда — устаревшим не бывает само число. Устаревает
  // только сведение «идёт ли проверка»: событие, отправленное ДО того, как
  // аудио-поток обработал нашу последнюю команду, игнорируем именно в этой
  // части (см. `эпоха_свежая` и её докблок).
  if (эпоха_свежая(l.epoch, известная_эпоха)) {
    const было = проверка_идёт;
    проверка_идёт = Boolean(l.monitoring);
    if (было !== проверка_идёт || $("mic-test").hidden === проверка_идёт) показать_проверку(проверка_идёт);
  }
}

// Число — через Intl.NumberFormat: он сам решает про запятую или точку в
// зависимости от языка. Единицы «Б/КБ/МБ/ГБ» — из словаря (раздел size).
function число(n, максимум_знаков) {
  return new Intl.NumberFormat(i18n.lang, { maximumFractionDigits: максимум_знаков ?? 0 }).format(n);
}

function размер(байты) {
  if (байты < 1024) return `${число(байты)} ${i18n.t("size.b")}`;
  const кб = байты / 1024;
  if (кб < 1024) return `${число(кб)} ${i18n.t("size.kb")}`;
  const мб = кб / 1024;
  // Десятая доля мегабайта при таком масштабе не значит ничего, а «1720.2 МБ»
  // ещё и плохо читается. От гигабайта один знак возвращаем — там он различим.
  return мб < 1024
    ? `${число(мб)} ${i18n.t("size.mb")}`
    : `${число(мб / 1024, 1)} ${i18n.t("size.gb")}`;
}

// Папка выводится в подвале меню записи, только если противоречит дате в имени.
// При совпадении она буквально повторяет первые семь символов имени, стоящего
// строкой выше, — информации ноль, место занято. Несовпадение же означает, что
// запись лежит не там: осталась в корне после незавершённой миграции или её
// двигали руками. Тогда это единственный признак, что стоит присмотреться.
function папка_аномальна(запись) {
  if (запись.folder == null) return i18n.t("folder.root");
  return запись.folder === запись.name.slice(0, 7) ? null : запись.folder;
}

