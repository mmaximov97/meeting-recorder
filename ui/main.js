// Единственное место, где в разметку попадает innerHTML, и попадают в него
// только константы выше — ни одна строка от пользователя (имя записи, имя
// устройства, текст ошибки) сюда не приходит: она ставится через textContent.
function значок(разметка, класс) {
  const el = document.createElement("span");
  if (класс) el.className = класс;
  el.innerHTML = разметка;
  return el;
}

