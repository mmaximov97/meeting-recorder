function сколько_идёт(с) {
  const минут = Math.floor((Date.now() - с) / 60000);
  return минут < 1 ? "меньше минуты" : `${минут} мин`;
}

// Стадия, которую ставит не бэкенд, а сам интерфейс — на время между кликом
// по «Расшифровать встречу» и первым событием прогресса. Без неё строка
// оставалась нетронутой, и человек открывал меню и жал второй раз. Подписи у
// неё своей нет: подпись_стадии отдаёт общее «Расшифровываю…», и оно не
// врёт — расшифровка действительно началась.
const СТАДИЯ_ЗАПУСК = "starting";

const СТАДИЯ_ПОДПИСЬ = {
  uploading: "Отправляю…",
  polling: "Расшифровываю…",
  merging: "Собираю текст…",
  done: "Готово",
};

// "queued:N" — не статичная стадия из СТАДИЯ_ПОДПИСЬ, а формат
// "queued:" + позиция (шлёт transcribe_recording при постановке в очередь,
// и воркер очереди — каждой оставшейся записи после того, как предыдущая
// закончилась и все позиции сдвинулись). Разбираем здесь же, а не заводим
// под это отдельную карту: позиция меняется, сама подпись — нет.
function подпись_стадии(стадия) {
  if (стадия?.startsWith("queued:")) {
    return `В очереди №${стадия.slice("queued:".length)}`;
  }
  return СТАДИЯ_ПОДПИСЬ[стадия] ?? "Расшифровываю…";
}

// Полоску прогресса рисуем только тогда, когда действительно что-то идёт.
// У записи в очереди ждать нечего показывать: ползущая полоска у трёх записей
// подряд читается как «все три обрабатываются», а обрабатывается одна.
function стадия_идёт(стадия) {
  return Boolean(стадия) && !стадия.startsWith("queued:") && стадия !== "done";
}

