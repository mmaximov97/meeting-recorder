// "queued:N" — не статичная стадия из СТАДИЯ_ПОДПИСЬ, а формат
// "queued:" + позиция (шлёт transcribe_recording при постановке в очередь,
// и воркер очереди — каждой оставшейся записи после того, как предыдущая
// закончилась и все позиции сдвинулись). Разбираем здесь же, а не заводим
// под это отдельную карту: позиция меняется, сама подпись — нет.
function подпись_стадии(стадия) {
  if (стадия?.startsWith("queued:")) {
    return `В очереди (${стадия.slice("queued:".length)})`;
  }
  return СТАДИЯ_ПОДПИСЬ[стадия] ?? "Идёт транскрипция…";
}

