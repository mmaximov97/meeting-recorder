// Пока окно скрыто в трее, WebView2 иногда не перерисовывает свои
// абсолютно позиционированные слои (заливка полоски через clip-path, пиковый
// маркер) — сам DOM и custom-property уже верные (обновляются событиями и
// тогда, когда окно не в фокусе), а нарисованный кадр остаётся старым до
// первого события, которое их снова тронет. Заливка потом сама «отпускает»
// с первым же levels, а маркер никто больше не трогает — так и висит
// неправильно нарисованным. display:none/restore синхронно, без паузы на
// отрисовку между ними, поэтому мигания не видно, а слой перерисовывается
// с нуля.
//
// Метров теперь два комплекта — полные в настройках и узкие в панели «идёт
// запись», — и баг одинаково цепляет оба, поэтому перерисовываются все.
function форсировать_перерисовку_метров() {
  for (const el of document.querySelectorAll(".disc")) {
    el.style.display = "none";
    void el.offsetHeight;
    el.style.display = "";
  }
}

// Окно живёт в трее и показывается спустя часы после загрузки страницы: без
// этого список остался бы тем, каким его собрали на старте приложения.
// Устройства подключают и отключают, пока окно закрыто, поэтому выпадашка
// обновляется тем же обработчиком.
window.addEventListener("focus", () => {
  обновить_список();
  обновить_устройства();
  форсировать_перерисовку_метров();
});

// `focus` не помогает, если гарнитуру подключили или отключили, пока окно уже
// открыто и в фокусе, — событие фокуса тогда попросту не случится, и выпадашка
// зависает такой, какой была на момент открытия окна. `devicechange` — штатное
// событие Web-платформы (Chromium/WebView2 и WKWebView его отдают), не требует
// разрешения на микрофон: список устройств сам приложение всё равно спрашивает
// у бэкенда через `list_mic_devices`, здесь оно нужно только как сигнал
// «что-то подключили/отключили, пойди перепроверь».
navigator.mediaDevices?.addEventListener("devicechange", обновить_устройства);

// Порядок здесь — не вкусовщина. Сначала подписки, потом снимок: подписавшись
// первыми, мы не пропустим изменение, случившееся во время запроса, а снимок
// следом покажет то, что случилось ДО подписки. Наоборот — оставило бы дырку
// ровно между двумя шагами.
//
// Снимок нужен именно потому, что Tauri не буферизует события: аудио-поток
// живёт с setup(), эта страница загружается позже (а после перезагрузки окна —
// намного позже), и всё, что он успел сообщить до нас, мы можем только спросить.
async function старт() {
  // Словарь и язык обязаны быть готовы раньше первой отрисовки — иначе все
  // t() ниже вернули бы голые ключи вместо текста.
  await window.i18n.ready;
  window.i18n.applyStatic();
  // Галочка «Скопировано» встаёт в разметку заранее, а не при первом
  // копировании: если бы кнопка панели меняла свою ширину в момент появления
  // значка, «Скопировать путь/текст» дёрнулась бы вбок ровно тогда, когда
  // человек за ней следит глазами.
  for (const узел of document.querySelectorAll(".ok-msg[data-ok]")) {
    узел.insertAdjacentHTML("afterbegin", ГАЛОЧКА(16));
  }
  // Заголовок нативного окна ставит конфиг (tauri.conf.json, статично и
  // по-английски — он не умеет читать словарь), а на реальный язык доводит
  // его этот вызов.
  getCurrentWindow()
    .setTitle(i18n.t("app.windowMain"))
    .catch(() => {});
  отрисовать_версию();
  for (const узел of document.querySelectorAll(".leds")) сегменты.собрать(узел);
  сегменты_выбора();
  показать_проверку(false);
  отрисовать_контакты("contacts-design", "contacts-design-soon", КОНТАКТЫ_ДИЗАЙН);
  отрисовать_контакты("contacts-code", "contacts-code-soon", КОНТАКТЫ_РАЗРАБОТКА);
  отрисовать_поддержку();

  await listen("state", (e) => применить_состояние(e.payload));
  // Само по себе событие ничего не показывает: строку взвода ставит
  // применить_состояние в момент перехода в «armed». Здесь только запоминаем,
  // кого услышали, — состояние придёт отдельным событием следом.
  await listen("ask", (e) => {
    const имя = String(e.payload ?? "");
    кто_звонит = ЗВОНИЛКИ[имя] ?? "";
  });
  await listen("error", (e) => показать_ошибку(i18n.t("error.audio"), e.payload));
  await listen("fatal", (e) => показать_фатальную(String(e.payload)));
  await listen("device-warning", (e) => показать_предупреждение_устройства(e.payload));
  await listen("mic-deferred", (e) => показать_отложенность(Boolean(e.payload)));
  await listen("mic-muted", (e) => показать_выключение_микрофона(Boolean(e.payload)));
  await listen("no-system-audio", (e) =>
    показать_отсутствие_системного_звука(e.payload),
  );
  await listen("levels", (e) => применить_уровни(e.payload));
  await listen("screen", (e) => показать_экран_на_пульте(e.payload));
  // Микрофон сменили на лету — подпись кнопки и зелёная строка на пульте.
  await listen("mic-switched", (e) => {
    const имя = e.payload?.name || i18n.t("pultmic.system");
    микрофон_записи = имя;
    отрисовать_кнопку_микрофона();
    вспышка_пульта(i18n.t("pultmic.flash", { name: имя }));
  });
  await listen("calendar-status", (e) => {
    календарь = e.payload;
    отрисовать_календарь();
  });
  await listen("update-available", (e) => показать_обновление(e.payload));
  await listen("update-progress", (e) => {
    // Событие и ответ команды идут разными путями, и последний процент может
    // догнать окно уже после отказа — отказ он затирать не должен.
    if (установка?.error) return;
    установка = { stage: e.payload.stage, percent: e.payload.percent };
    отрисовать_обновление();
  });
  await listen("transcribe-progress", (e) => {
    const ключ = ключ_транскрипции(e.payload.folder, e.payload.base);
    транскрипции.set(ключ, e.payload.stage);
    обновить_список();
    // Панель этой же записи открыта — баннер «Расшифровываю заново» должен
    // появиться сразу, а не ждать transcribe-done: до этого момента панель
    // честно показывает прошлую версию текста.
    обновить_баннер_панели(ключ);
  });
  await listen("transcribe-track", (e) => {
    детали_расшифровки.set(ключ_транскрипции(e.payload.folder, e.payload.base), {
      дорожка: e.payload.track,
      с: Date.now(),
    });
    обновить_список();
  });
  await listen("transcribe-done", (e) => {
    const ключ = ключ_транскрипции(e.payload.folder, e.payload.base);
    транскрипции.set(ключ, "done");
    детали_расшифровки.delete(ключ);
    обновить_список();
    // Панель той же записи открыта — новый текст должен появиться сам, без
    // повторного клика по строке: с точки зрения панели это ровно то же
    // событие, что уже перерисовало строку списка.
    перезагрузить_панель_после_расшифровки(e.payload.folder, e.payload.base, ключ);
    setTimeout(() => {
      транскрипции.delete(ключ);
      обновить_список();
    }, 3000);
  });
  // Отмена — не ошибка: человек нажал её сам, и красное «не удалось» на своё
  // же действие читается как сбой. Поэтому строка просто возвращается к тому,
  // какой была до расшифровки, и ничего не объявляет.
  await listen("transcribe-cancelled", (e) => {
    const ключ = ключ_транскрипции(e.payload.folder, e.payload.base);
    транскрипции.delete(ключ);
    детали_расшифровки.delete(ключ);
    обновить_список();
    обновить_баннер_панели(ключ);
  });
  await listen("transcribe-error", (e) => {
    const ключ = ключ_транскрипции(e.payload.folder, e.payload.base);
    транскрипции.delete(ключ);
    детали_расшифровки.delete(ключ);
    // Ошибка показывается там, где сломалось, — карточкой у самой записи,
    // а не общей строкой внизу экрана.
    ошибки_расшифровки.set(ключ, e.payload.message);
    обновить_список();
    обновить_баннер_панели(ключ);
  });
  // Скачивание модели локальной расшифровки — три события, тем же приёмом,
  // что и расшифровка записи выше (прогресс/готово/ошибка), только не по
  // записи, а по одной-единственной модели, поэтому без ключа и без карты.
  await listen("local-model-progress", (e) => {
    модель_состояние = { state: "downloading", done: e.payload.done, total: e.payload.total };
    отрисовать_модель();
  });
  await listen("local-model-done", () => {
    модель_скачивается = false;
    обновить_статус_модели();
  });
  await listen("local-model-error", (e) => {
    модель_скачивается = false;
    // `local.noSpace` приходит с числами и своим состоянием (без кнопки
    // повтора — здесь нечего повторять, пока место не освободили); всё
    // остальное — общий `downloadFailed` с кнопкой «Попробовать снова».
    модель_состояние =
      e.payload.key === "local.noSpace"
        ? { state: "no_space", need: e.payload.need, free: e.payload.free }
        : { state: "failed" };
    отрисовать_модель();
  });

  try {
    const снимок = await invoke("get_state");
    применить_состояние(снимок.state);
    if (снимок.fatal) показать_фатальную(снимок.fatal);
    показать_предупреждение_устройства(снимок.device_warning);
    показать_отложенность(Boolean(снимок.mic_deferred));
    // Окно, открытое посреди встречи с выключенным микрофоном, обязано сразу
    // показать его выключенным: событие о выключении ушло до нас.
    показать_выключение_микрофона(Boolean(снимок.mic_muted));
    // Через снимок, а не только по событию: отказ случается в setup(), то есть
    // раньше, чем webview успевает подписаться, — и после перезагрузки
    // страницы событие уже не повторится.
    показать_отсутствие_системного_звука(снимок.no_system_audio);
  } catch (e) {
    показать_ошибку(i18n.t("error.state"), e);
  }

  // Обновление — тем же приёмом, что снимок состояния выше: проверка идёт в
  // фоне с первой секунды, и её событие могло уйти до подписки. Отказ здесь
  // молчит: баннер обновления — не то, ради чего показывать ошибку.
  try {
    встроенная_установка = Boolean(await invoke("update_in_app"));
  } catch {
    встроенная_установка = false;
  }
  try {
    показать_обновление(await invoke("update_status"));
  } catch {
    показать_обновление(null);
  }

  // Пока идёт расшифровка, в интерфейс ничего не прилетает: стадия шлётся один
  // раз, дорожка — по разу на дорожку, а сам опрос шлюза длится часами молча.
  // Без этого таймера подпись «12 мин» замерла бы на значении, которое было в
  // момент прихода события, и врала бы тем сильнее, чем дольше идёт работа.
  // Полминуты — с запасом: подпись всё равно округлена до минут.
  const ШАГ_ПЕРЕРИСОВКИ_РАСШИФРОВКИ = 30000;
  setInterval(() => {
    for (const стадия of транскрипции.values()) {
      if (стадия_идёт(стадия)) {
        обновить_список();
        return;
      }
    }
  }, ШАГ_ПЕРЕРИСОВКИ_РАСШИФРОВКИ);

  // Безусловно, хотя применить_состояние выше могло уже дёрнуть список: в Armed
  // и в записи оно этого не делает, а показать прошлые записи надо в любом
  // состоянии. Лишний read_dir на старте дешевле, чем связка с чужим условием,
  // которая молча оставит список пустым, если то условие однажды поменяется.
  обновить_список();
  обновить_устройства();
}

старт();
