function отрисовать_контакты(id_списка, id_заглушки, контакты) {
  const ul = $(id_списка);
  ul.innerHTML = "";
  for (const { label, url } of контакты) {
    const li = document.createElement("li");
    const кнопка = document.createElement("button");
    кнопка.type = "button";
    кнопка.className = "btn-link";
    кнопка.textContent = label;
    кнопка.addEventListener("click", () => открыть_ссылку(url));
    li.appendChild(кнопка);
    ul.appendChild(li);
  }
  ul.hidden = контакты.length === 0;
  $(id_заглушки).hidden = контакты.length > 0;
}

