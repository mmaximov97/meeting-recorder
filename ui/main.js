// Ядро отдаёт линейный пик 0..1 — это физическая амплитуда, и её умышленно
// не трогаем: на macOS этим же числом (`app.levels()`) гейтится детект
// звонка по звуку (`audio.rs::detect.step`), и калибровать там нужно линейный
// пик, а не то, как он выглядит в полоске. В линейном виде это же число почти
// всегда «пустая» полоска: нормальная речь на здоровом уровне записи редко
// превышает четверть-треть от полного размаха, а не половину. Переводим в
// дБFS и показываем от -60 дБ (тихо, но видно шевеление) до 0 дБ (потолок,
// клиппинг) — тот же диапазон, что у большинства аудиоредакторов и микшеров.
const МЕТР_ПОЛ_ДБ = -60;

function уровень_в_проценты(линейный) {
  if (линейный <= 0) return 0;
  const db = 20 * Math.log10(линейный);
  return Math.min(100, Math.max(0, ((db - МЕТР_ПОЛ_ДБ) / -МЕТР_ПОЛ_ДБ) * 100));
}

function применить_уровни(l) {
  $("lvl-mic").style.width = `${уровень_в_проценты(l.mic)}%`;
  $("lvl-sys").style.width = `${уровень_в_проценты(l.system)}%`;
  проверка_идёт = Boolean(l.monitoring);
  $("check").textContent = проверка_идёт ? "Остановить проверку" : "Проверить";
}

function размер(байты) {
  if (байты < 1024) return `${байты} Б`;
  const кб = байты / 1024;
  if (кб < 1024) return `${кб.toFixed(0)} КБ`;
  const мб = кб / 1024;
  // Десятая доля мегабайта при таком масштабе не значит ничего, а «1720.2 МБ»
  // ещё и плохо читается. От гигабайта один знак возвращаем — там он различим.
  return мб < 1024 ? `${Math.round(мб)} МБ` : `${(мб / 1024).toFixed(1)} ГБ`;
}

// Папка выводится в строке записи, только если противоречит дате в имени.
// При совпадении она буквально повторяет первые семь символов имени, стоящего
// строкой выше, — информации ноль, место занято. Несовпадение же означает, что
// запись лежит не там: осталась в корне после незавершённой миграции или её
// двигали руками. Тогда это единственный признак, что стоит присмотреться.
function папка_аномальна(запись) {
  if (запись.folder == null) return "в корне";
  return запись.folder === запись.name.slice(0, 7) ? null : запись.folder;
}

function применить_состояние(s) {
  $("state").textContent = ПОДПИСЬ[s] ?? s;
  $("lamp").className = `lamp ${s}`;
  $("toggle").textContent = s === "recording" ? "Остановить запись" : "Начать запись";
  // Вопрос живёт ровно столько, сколько Armed: ушла сессия или пришёл ответ —
  // баннер обязан исчезнуть сам, иначе на экране останется вопрос, на который
  // уже некому отвечать.
  $("ask").classList.toggle("on", s === "armed");
  if (s !== "recording" && s !== "armed") обновить_список();
  if (s === "idle" && !проверка_идёт) {
    применить_уровни({ mic: 0, system: 0, monitoring: false });
  }
}

async function обновить_список() {
  try {
    const записи = await invoke("list_recordings");
    const list = $("list");
    list.innerHTML = "";
    if (записи.length === 0) {
      const li = document.createElement("li");
      li.className = "empty";
      li.textContent = "Пока пусто";
      list.append(li);
      return;
    }
    for (const з of записи) {
      const li = document.createElement("li");
      const имя = document.createElement("div");
      имя.className = "name";
      имя.textContent = з.name;
      // Имя обрезается многоточием (см. `.name` в стилях) — полное отдаём
      // подсказкой, иначе после переименования его будет не прочитать.
      имя.title = з.name;
      const мета = document.createElement("div");
      мета.className = "meta";
      // Отсутствие дорожки — не косметика: пара mic+system и есть запись.
      const дорожки = [з.mic ? "mic" : null, з.system ? "system" : null].filter(Boolean);
      const части = [дорожки.join(" + "), размер(з.size)];
      const аномалия = папка_аномальна(з);
      if (аномалия) части.unshift(аномалия);
      мета.textContent = части.join(" · ");
      if (!з.mic || !з.system) {
        мета.classList.add("warn");
        мета.textContent += " · дорожка отсутствует";
      }
      if (з.imbalance_db != null) {
        мета.classList.add("warn");
        мета.textContent += ` · микрофон тише на ${Math.round(з.imbalance_db)} дБ`;
      }
      const колонка = document.createElement("div");
      колонка.className = "grow";
      колонка.append(имя, мета);

      const ключ = ключ_транскрипции(з.folder, з.name);
      const стадия = транскрипции.get(ключ);

      const кнопка = document.createElement("button");
      кнопка.className = "rename";
      кнопка.textContent = "Переименовать";
      if (стадия) {
        кнопка.disabled = true;
      } else {
        кнопка.addEventListener("click", () => начать_переименование(з, имя, кнопка));
      }

      if (з.mic && з.system) {
        const кнопкаТранскрипции = document.createElement("button");
        кнопкаТранскрипции.className = "rename";
        if (стадия) {
          кнопкаТранскрипции.textContent = подпись_стадии(стадия);
          кнопкаТранскрипции.disabled = true;
        } else {
          кнопкаТранскрипции.textContent = "Транскрибировать";
          кнопкаТранскрипции.addEventListener("click", () => начать_транскрипцию(з));
        }
        li.append(колонка, кнопка, кнопкаТранскрипции);
      } else {
        li.append(колонка, кнопка);
      }
      list.append(li);
    }
  } catch (e) {
    показать_ошибку(String(e));
  }
}

// Префикс с датой не редактируется: по нему идёт сортировка списка, склейка
// пары дорожек и выбор месячной папки. Поле правит только хвост.
const ДЛИНА_ПРЕФИКСА = 17;

function начать_переименование(запись, узел_имени, кнопка) {
  const префикс = запись.name.slice(0, ДЛИНА_ПРЕФИКСА);
  const хвост = запись.name.slice(ДЛИНА_ПРЕФИКСА);
  узел_имени.textContent = префикс;
  // Снимает обрезку многоточием на время правки: иначе поле ввода, шириной во
  // весь контейнер, не помещается рядом с префиксом и срезается `overflow`.
  // Класс не убираем — `обновить_список` пересобирает строку целиком.
  узел_имени.classList.add("editing");
  // Полное имя в подсказке относится к обычному состоянию; в режиме правки оно
  // только мешает, перекрывая поле всплывашкой.
  узел_имени.removeAttribute("title");
  const поле = document.createElement("input");
  поле.className = "tail-input";
  поле.value = хвост;
  узел_имени.append(поле);
  поле.focus();
  поле.select();
  кнопка.disabled = true;

  // обновить_список() ниже перерисовывает <ul> целиком — list.innerHTML = ""
  // синхронно выбрасывает из документа ещё сфокусированное поле, а удаление
  // сфокусированного элемента само порождает событие blur. Без флага и без
  // снятия слушателя это било дважды: Escape вместо отмены применял текущее
  // (не отменённое) значение поля через blur-обработчик, а обычное
  // применение через Enter задваивалось тем же blur'ом секундой позже.
  // Флаг закрывает вход и в третьем случае — быстрый повторный Enter или
  // Tab/клик до ответа сервера тоже не даёт второй invoke.
  let завершено = false;

  const отписаться = () => поле.removeEventListener("blur", на_потерю_фокуса);

  const применить = async () => {
    if (завершено) return;
    завершено = true;
    отписаться();
    поле.disabled = true;
    try {
      await invoke("rename_recording", {
        folder: запись.folder ?? null,
        base: запись.name,
        newTail: поле.value,
      });
      показать_ошибку("");
    } catch (e) {
      показать_ошибку(String(e));
    }
    обновить_список();
  };

  const отменить = () => {
    if (завершено) return;
    завершено = true;
    отписаться();
    обновить_список();
  };

  const на_потерю_фокуса = () => применить();

  поле.addEventListener("keydown", (e) => {
    if (e.key === "Enter") применить();
    if (e.key === "Escape") отменить();
  });
  поле.addEventListener("blur", на_потерю_фокуса);
}

