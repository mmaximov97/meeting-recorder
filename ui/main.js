// ── Свой тултип у значка-вопросика ──────────────────────────────────────
// Заменяет системный `title`: тот появляется с задержкой в секунду и
// выглядит чужим. Пузырь один на всё окно (`#tip-bubble`, конец <body>) и
// позиционируется `position: fixed` по факту через `getBoundingClientRect` —
// не CSS-координатами относительно значка: тело настроек прокручивается, и
// значок может стоять где угодно по вертикали. Если сверху не хватает места,
// пузырь разворачивается вниз (см. класс `.below` в index.html).
{
  const тултип_триггер = $("local-about");
  const тултип_пузырь = $("tip-bubble");
  const тултип_область = document.querySelector("#screen-settings .body");

  function позиционировать_подсказку() {
    const триг = тултип_триггер.getBoundingClientRect();
    const зазор = 9;
    const край = 8;
    const ширина = 262;
    тултип_пузырь.style.width = `${ширина}px`;
    const высота = тултип_пузырь.offsetHeight;
    let слева = триг.left + триг.width / 2 - ширина / 2;
    слева = Math.max(край, Math.min(слева, window.innerWidth - ширина - край));
    let сверху = триг.top - зазор - высота;
    let снизу = false;
    // Не хватает места над значком — разворачиваем вниз, как в мокапе.
    if (сверху < край) {
      сверху = триг.bottom + зазор;
      снизу = true;
    }
    тултип_пузырь.style.left = `${слева}px`;
    тултип_пузырь.style.top = `${сверху}px`;
    const стрелка = триг.left + триг.width / 2 - слева;
    тултип_пузырь.style.setProperty(
      "--arrow-left",
      `${Math.max(12, Math.min(ширина - 12, стрелка))}px`,
    );
    тултип_пузырь.classList.toggle("below", снизу);
  }

  function показать_подсказку() {
    // Текст читается заново при каждом показе — он всегда в языке, который
    // выбран сейчас, без отдельной подписки на смену языка.
    $("tt-t1").textContent = i18n.t("local.onServer");
    $("tt-x1").textContent = i18n.t("local.serverHint");
    $("tt-t2").textContent = i18n.t("local.onDevice");
    $("tt-x2").textContent = i18n.t("local.hint");
    $("tt-note").textContent = i18n.t("local.noDiarization");
    позиционировать_подсказку();
    тултип_пузырь.classList.add("open");
  }

  function скрыть_подсказку() {
    тултип_пузырь.classList.remove("open");
  }

  тултип_триггер.addEventListener("mouseenter", показать_подсказку);
  тултип_триггер.addEventListener("mouseleave", скрыть_подсказку);
  тултип_триггер.addEventListener("focus", показать_подсказку);
  тултип_триггер.addEventListener("blur", скрыть_подсказку);
  // Прокрутка тела настроек уносит значок — пузырь остался бы висеть не над
  // ним. Прячем, а не двигаем следом: пересчитывать позицию на каждый кадр
  // скролла ради тултипа не стоит того.
  тултип_область?.addEventListener("scroll", скрыть_подсказку, { passive: true });
  window.addEventListener("resize", скрыть_подсказку);
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && тултип_пузырь.classList.contains("open")) скрыть_подсказку();
  });
}

// Подтверждение сохранения — строка рядом с тем, что сохранили, не тост и не
// модалка. Мест таких два: под полями расшифровки и под выпадашкой микрофона.
// Тост в углу окна тут не годится — он одинаково далеко от обоих.
const таймеры_сохранено = new Map();

function показать_сохранено(id) {
  const el = $(id);
  el.hidden = false;
  // Перезапуск анимации: второе сохранение подряд иначе не мигнёт, и человек
  // не поймёт, что оно вообще случилось второй раз.
  el.style.animation = "none";
  void el.offsetHeight;
  el.style.animation = "";
  clearTimeout(таймеры_сохранено.get(id));
  таймеры_сохранено.set(
    id,
    setTimeout(() => {
      el.hidden = true;
      таймеры_сохранено.delete(id);
    }, 2500),
  );
}

