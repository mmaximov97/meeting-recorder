// имя УЖЕ ЗАПИСАННОГО файла (исторический формат, застывший в именах на
// диске — там обязаны жить оба написания, macOS и Windows), а ЗВОНИЛКИ читает
// id из СОБЫТИЯ прямо сейчас (живой формат — один канонический id на обе
// системы). Таблица повторяет ui/ask.js — правишь здесь, правь и там, иначе
