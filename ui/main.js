// ─────────────────────────────────────────────────────────────────────────────
// Настройки
//
// Значение <option> — идентификатор эндпоинта, подпись — имя. Пользователь
// выбирает глазами по имени, приложение запоминает идентификатор: имя может
// поменяться в настройках Windows, идентификатор — нет.
async function обновить_устройства() {
  try {
    const [устройства, конфиг] = await Promise.all([
      invoke("list_mic_devices"),
      invoke("get_config"),
    ]);
    const sel = $("mic");
    sel.innerHTML = "";
    const дефолт = document.createElement("option");
    дефолт.value = "";
    дефолт.textContent = i18n.t("settings.micFromSystem");
    sel.append(дефолт);
    for (const у of устройства) {
      const o = document.createElement("option");
      o.value = у.id;
      o.textContent = у.name;
      sel.append(o);
    }
    // Сохранённое устройство может отсутствовать прямо сейчас (гарнитура
    // выключена) — тогда его вообще нет среди `устройства`, и `sel.value`
    // ниже просто не находит совпадения: браузер откатывает выпадашку на
    // первый пункт, «Системный по умолчанию». Саму настройку это не трогает —
    // `set_mic_device` шлётся только по явному `change` пользователем
    // (см. ниже), а не потому что список перерисовался; если гарнитуру
    // включат обратно, `обновить_устройства` (по фокусу окна или
    // `devicechange`) снова найдёт её в списке и подсветит как выбранную.
    // О том, что запись реально пишется не тем устройством, отдельно
    // предупреждает баннер `#devwarn` — он держит это состояние честно,
    // а не выпадашка.
    const сохранён = конфиг.mic_device_id ?? "";
    sel.value = сохранён;
    // Пока смена отложена, в конфиге уже НОВЫЙ микрофон, а подписи нужен тот,
    // которым пишется идущая запись, — поэтому здесь не трогаем.
    if (!смена_отложена) сохранённый_микрофон = конфиг.mic_device_name ?? null;
    $("stt-url").value = конфиг.stt_gateway_url ?? "";
    $("stt-key").value = конфиг.stt_api_key ?? "";
    $("lang").value = конфиг.language ?? "system";
    $("theme").value = конфиг.theme ?? "system";
    $("retention").value =
      конфиг.audio_retention_days != null ? String(конфиг.audio_retention_days) : "never";
    // Пока локального движка нет, режим не предлагается и сохранённое
    // «local» показывается как сервер — ровно так его и трактует Rust
    // (`transcribe::effective_mode`). Иначе человек выбрал бы режим, скачал
    // бы «модель» с адреса-заглушки и упёрся бы в «движок не подключён».
    const режим = ЛОКАЛЬНЫЙ_РЕЖИМ_ДОСТУПЕН ? (конфиг.transcribe_mode ?? "server") : "server";
    $("transcribe-mode").value = режим;
    применить_режим_расшифровки(режим);
    const тип_сервера = конфиг.transcribe_server === "whisper_cpp" ? "whisper_cpp" : "gateway";
    $("transcribe-server").value = тип_сервера;
    применить_тип_сервера(тип_сервера);
    await загрузить_экран();
    отрисовать_кнопку_микрофона();
    сегменты_выбора();
    обновить_календарь();
  } catch (e) {
    показать_ошибку(i18n.t("error.mics"), e);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// Сегменты выбора (`.sg[data-for]`)
//
// Источник правды — спрятанный <select> с тем же id, что и раньше: его
// значение ставит обновить_устройства, его `change` слушают обработчики ниже.
// Сегменты только показывают значение и по клику ставят новое, посылая тот
// же `change`. Подписи берутся из <option> — их переводит applyStatic.
function сегменты_выбора() {
  for (const группа of document.querySelectorAll(".sg[data-for]")) {
    const sel = $(группа.dataset.for);
    const подпись = JSON.stringify([...sel.options].map((o) => [o.value, o.textContent.trim()]));
    if (группа.dataset.sig !== подпись) {
      группа.dataset.sig = подпись;
      группа.replaceChildren();
      for (const o of sel.options) {
        const b = document.createElement("button");
        b.type = "button";
        b.dataset.value = o.value;
        b.textContent = o.textContent.trim();
        b.addEventListener("click", () => {
          if (sel.value === o.value) return;
          sel.value = o.value;
          sel.dispatchEvent(new Event("change"));
          сегменты_выбора();
        });
        группа.append(b);
      }
    }
    for (const b of группа.children) b.setAttribute("aria-pressed", String(b.dataset.value === sel.value));
  }
}

