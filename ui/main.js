// Запись и взвод — не время для перезапуска. Кнопка гаснет заранее, а
// бэкенд всё равно перепроверяет (`ensure_idle` в main.rs): запись может
// начаться и после нажатия.
function занято_записью() {
  return предыдущее_состояние === "recording" || предыдущее_состояние === "armed";
}

// Отказ приходит ключом строки и подробностью (`update::UpdateError`).
// Подробность уходит в подсказку по наведению, как у остальных баннеров; у
// «нет прав на папку» она же — сама папка в тексте. Не объект — сломался сам
// вызов, а не установка: общая фраза.
function текст_отказа(e) {
  if (e && typeof e === "object" && e.key) return i18n.t(e.key, { detail: e.detail ?? "" });
  return i18n.t("error.generic");
}
function подробность_отказа(e) {
  return String((e && typeof e === "object" ? e.detail : e) ?? "");
}

function текст_установки() {
  if (установка.error) return текст_отказа(установка.error);
  if (установка.stage === "downloading")
    return i18n.t("update.downloading", { p: установка.percent ?? 0 });
  if (установка.stage === "restarting") return i18n.t("update.restarting");
  return i18n.t("update.installing");
}

function подсказка(узел, текст) {
  if (текст) узел.title = текст;
  else узел.removeAttribute("title");
}

// Релиз, который предлагают настройки: ответ ручной проверки, если она была,
// иначе тот, что нашла фоновая (баннер). «Позже» в баннере гасит его и здесь —
// до следующей ручной проверки, которая «Позже» не учитывает.
function релиз_в_настройках() {
  if (ручная_проверка && "latest" in ручная_проверка) return ручная_проверка.latest;
  return обновление;
}

function отрисовать_обновление() {
  const идёт = Boolean(установка && !установка.error);
  const отказ = установка?.error ?? null;
  const подсказка_записи = занято_записью() ? i18n.t("update.errRecording") : "";

  слот("s-update", Boolean(обновление));
  const текст = $("update-text");
  текст.textContent = !обновление
    ? ""
    : установка
      ? текст_установки()
      : i18n.t("update.available", { v: обновление.version });
  подсказка(текст, обновление && отказ ? подробность_отказа(отказ) : "");
  // После отказа баннер ведёт на страницу релиза: повторить можно из
  // настроек, а ручная установка сработает при любой причине отказа.
  // Пока ставится, «Обновить» не прячется, а гаснет — как любая кнопка по
  // клику (см. нажать), и баннер не прыгает по высоте; «Позже» уже не к месту.
  const ставим_сами = встроенная_установка && !отказ;
  const кнопка = $("update-open");
  кнопка.textContent = i18n.t(ставим_сами ? "update.install" : "update.download");
  кнопка.disabled = идёт || (ставим_сами && Boolean(подсказка_записи));
  подсказка(кнопка, ставим_сами ? подсказка_записи : "");
  $("update-later").hidden = идёт;

  const релиз = релиз_в_настройках();
  let строка = "";
  let тревога = false;
  let причина = "";
  if (установка) {
    строка = текст_установки();
    тревога = Boolean(отказ);
    причина = отказ ? подробность_отказа(отказ) : "";
  } else if (ручная_проверка?.checking) {
    строка = i18n.t("update.checking");
  } else if (ручная_проверка?.error) {
    строка = текст_отказа(ручная_проверка.error);
    тревога = true;
    причина = подробность_отказа(ручная_проверка.error);
  } else if (релиз) {
    строка = i18n.t("update.available", { v: релиз.version });
  } else if (ручная_проверка) {
    строка = i18n.t("update.upToDate", { v: ручная_проверка.current });
  }
  const статус = $("upd-status");
  статус.textContent = строка;
  статус.hidden = !строка;
  // Жёлтый, не красный: не проверилось или не поставилось — это «попробуйте
  // ещё раз или вручную», а не поломка (см. .hint.warn).
  статус.classList.toggle("warn", тревога);
  подсказка(статус, причина);

  $("upd-check").disabled = идёт || Boolean(ручная_проверка?.checking);
  $("upd-install").hidden = !(встроенная_установка && релиз);
  $("upd-install").disabled = идёт || Boolean(подсказка_записи);
  подсказка($("upd-install"), подсказка_записи);
  $("upd-download").hidden = !(релиз && !идёт && (!встроенная_установка || отказ));
}

