// Состояние машины
//
// Таймер записи считается здесь, а не приходит из бэкенда: момента начала в
// снимке (`status::Snapshot`) нет. Поэтому число показывается только тогда,
// когда окно своими глазами видело переход в запись. Открыли окно из трея
// посреди встречи — таймера нет, но подпись «Запись идёт» есть: лучше не
// показать число, чем показать выдуманное.
let запись_началась = null;
let тик_таймера = null;
let первое_состояние = true;

function формат_таймера(мс) {
  const всего = Math.floor(мс / 1000);
  const ч = Math.floor(всего / 3600);
  const м = Math.floor((всего % 3600) / 60);
  const с = всего % 60;
  const мм_сс = `${String(м).padStart(2, "0")}:${String(с).padStart(2, "0")}`;
  return ч ? `${ч}:${мм_сс}` : мм_сс;
}

function обновить_таймер() {
  if (запись_началась == null) return;
  $("rec-timer").textContent = формат_таймера(Date.now() - запись_началась);
}

function запустить_таймер(известно_начало) {
  остановить_таймер();
  запись_началась = известно_начало ? Date.now() : null;
  $("rec-timer").hidden = !известно_начало;
  if (!известно_начало) return;
  обновить_таймер();
  тик_таймера = setInterval(обновить_таймер, 1000);
}

function остановить_таймер() {
  if (тик_таймера != null) clearInterval(тик_таймера);
  тик_таймера = null;
  запись_началась = null;
  $("rec-timer").hidden = true;
}

let предыдущее_состояние = null;

function применить_состояние(s) {
  const было_записью = предыдущее_состояние === "recording";
  const стало_записью = s === "recording";

  // Строка взвода живёт ровно столько, сколько Armed: ушла сессия или пришёл
  // ответ — она обязана исчезнуть сама, иначе на экране останется ожидание
  // ответа, которого уже никто не ждёт.
  const стало_взводом = s === "armed";
  слот("s-ask", стало_взводом);
  $("no").disabled = false;

  if (стало_взводом && предыдущее_состояние !== "armed") {
    // Текст ставится здесь, а не по событию `ask` и не в разметке: живая
    // область (role="status") озвучивает СМЕНУ текста, а не то, что готовый
    // текст стал видимым, — иначе появление взвода прошло бы молча.
    $("ask-q").textContent = кто_звонит
      ? `Похоже, встреча в ${кто_звонит}`
      : "Похоже, встреча";
    // Фокус переезжает на кнопку записи — во взводе это и есть ответ «да».
    // Ровно в момент перехода, а не на каждое событие состояния: иначе он
    // выдёргивался бы из поля правки имени и из настроек.
    if (!правка_идёт && !фатально) {
      // Слот только что получил класс `open`, но в дереве отрисовки кнопка ещё
      // `visibility: hidden` — а невидимому элементу движок фокус не даёт,
      // молча. Чтение offsetHeight заставляет пересчитать стили здесь и
      // сейчас; тот же приём стоит в открыть_меню по той же причине.
      void $("rec-btn").offsetHeight;
      $("rec-btn").focus();
    }
  } else if (!стало_взводом) {
    кто_звонит = "";
  }

  слот("s-record", !стало_записью);
  слот("s-recpanel", стало_записью);

  if (стало_записью && !было_записью) {
    // Первое применение состояния — это снимок из get_state: он говорит «идёт
    // запись», но не говорит, когда она началась.
    запустить_таймер(!первое_состояние);
    $("rec-panel").classList.remove("stopping");
    $("stop-btn").disabled = false;
    $("stop-btn-label").textContent = "Остановить";
    // Подпись ставится отсюда, а не стоит в разметке: живая область
    // (role="status" у #rec-lbl) озвучивает смену текста, а не то, что
    // готовый текст стал видимым. Статичная подпись здесь молчала бы.
    $("rec-lbl").textContent = "Запись идёт";
  } else if (!стало_записью && было_записью) {
    остановить_таймер();
    $("rec-lbl").textContent = "";
  }

  if (!стало_записью) {
    $("rec-btn").disabled = фатально;
    $("rec-btn-label").textContent = "Начать запись";
  }

  предыдущее_состояние = s;
  первое_состояние = false;

  if (s !== "recording" && s !== "armed") обновить_список();
  if (s === "idle" && !проверка_идёт) {
    // Без явного сброса пик просто «сполз» бы на пару дБ (обновить_пик вызовется
    // один раз, а не по тику) и завис — вместо мгновенного возврата к -∞.
    сбросить_пики();
    применить_уровни({ mic: 0, system: 0, monitoring: false });
  }
}

