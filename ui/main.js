// Статус — по факту на диске и по свободному месту (см. `local_model_status`
// в Rust), не то, что помнит фронтенд между запусками: модель могли удалить
// руками, скачивание — прервать закрытием ноутбука.
async function обновить_статус_модели() {
  if (модель_скачивается) return;
  try {
    модель_состояние = await invoke("local_model_status");
  } catch (e) {
    модель_состояние = null;
  }
  отрисовать_модель();
}

// Пять состояний из задачи: нет / качается / готова / не хватает места / не
// скачалась. Собирается в DOM тем же приёмом, что `собрать_меню` — узлы
// создаются заново, а не прячутся классом, разметки под все пять сразу в
// index.html нет.
function отрисовать_модель() {
  const тело = $("local-model-body");
  тело.innerHTML = "";
  const с = модель_состояние;
  if (!с) return;

  const текст = document.createElement("div");
  текст.className = "hint";
  тело.append(текст);

  if (с.state === "missing") {
    модель_известный_размер = с.size;
    текст.textContent = i18n.t("local.modelMissing");
    const кнопка = document.createElement("button");
    кнопка.className = "btn local-model-action";
    кнопка.textContent = i18n.t("local.modelDownload", { size: размер(с.size) });
    кнопка.addEventListener("click", скачать_модель);
    тело.append(кнопка);
  } else if (с.state === "downloading") {
    текст.textContent = i18n.t("local.modelLoading", {
      done: размер(с.done),
      total: размер(с.total),
    });
    const полоска = document.createElement("div");
    полоска.className = "prog local-model-action";
    полоска.append(document.createElement("i"));
    тело.append(полоска);
  } else if (с.state === "ready") {
    модель_известный_размер = с.size;
    текст.textContent = i18n.t("local.modelReady", { size: размер(с.size) });
    const кнопка = document.createElement("button");
    кнопка.className = "btn local-model-action";
    кнопка.textContent = i18n.t("local.modelRemove");
    кнопка.addEventListener("click", удалить_модель);
    тело.append(кнопка);
  } else if (с.state === "no_space") {
    // Жёлтый (--warn), не красный: не хватает места и не скачалась модель —
    // это «попробуйте ещё раз», а не поломка (см. .hint.warn в index.html).
    текст.classList.add("warn");
    текст.textContent = i18n.t("local.noSpace", { need: размер(с.need), free: размер(с.free) });
  } else if (с.state === "failed") {
    текст.classList.add("warn");
    текст.textContent = i18n.t("local.downloadFailed");
    const кнопка = document.createElement("button");
    кнопка.className = "btn local-model-action";
    кнопка.textContent = i18n.t("trouble.retry");
    кнопка.addEventListener("click", скачать_модель);
    тело.append(кнопка);
  }
}

async function скачать_модель() {
  модель_скачивается = true;
  // До первого события local-model-progress вес неизвестен — берём тот, что
  // уже показывали в «Модель не скачана, {size}»/«Модель на месте, {size}»,
  // а до него самого — 0: событие с настоящими числами приходит почти сразу,
  // до того, как реально польётся первый байт по сети.
  модель_состояние = { state: "downloading", done: 0, total: модель_известный_размер ?? 0 };
  отрисовать_модель();
  try {
    await invoke("local_model_download");
  } catch (e) {
    модель_скачивается = false;
    модель_состояние = { state: "failed" };
    отрисовать_модель();
  }
}

async function удалить_модель() {
  try {
    await invoke("local_model_remove");
    await обновить_статус_модели();
  } catch (e) {
    показать_ошибку(i18n.t("error.generic"), e);
  }
}

